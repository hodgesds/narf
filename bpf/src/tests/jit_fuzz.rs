/// Generate an arena program from `seed`, plus the page count of its arena.
///
/// Straight-line by construction. The arena lowering has no control flow in it,
/// and a loop over an arena would be a read-modify-write whose result depended
/// on which run went first — the native run's stores are still there when the
/// interpreted run starts, because both runs share one arena.
///
/// Every load is preceded by a store to the same effective address for the same
/// reason, so the value a load returns is a function of this program alone.
fn generate_arena(seed: u64, pages: usize) -> Vec<Decoded> {
    let mut rng = Rng::new(seed);
    let bytes = pages * 4096;
    let mut prog: Vec<Decoded> = Vec::new();

    // R0 := the arena base handle; parked in R6, which survives a call.
    prog.push(call_arena_base());
    prog.push(super::mov_reg(6, 0));
    // R0 is overwritten immediately because it still holds the *handle*, and
    // the program may end without ever loading into it — at which point `exit`
    // would be returning a pointer and the verifier refuses the program. That
    // is where the arena fuzzer's first measured verify rate of 94% went; the
    // rate is printed every run precisely so a gap like this is a number rather
    // than a guess.
    prog.push(super::mov_imm(0, rng.imm()));
    // The call clobbered R1..R5.
    for k in 1..=5u8 {
        prog.push(super::mov_imm(k, rng.imm()));
    }
    for k in 7..10u8 {
        prog.push(super::mov_imm(k, rng.imm()));
    }

    // Optional pointer arithmetic on the handle, so the displacement fold is
    // not the only thing addressing the arena.
    let mut bump: i64 = 0;
    if rng.chance(40) {
        // A page-aligned bump that leaves room for the accesses below.
        let b = (rng.below((pages as u32).max(1)) * 4096) as i64;
        if b > 0 {
            prog.push(super::alu_imm(AluOp::Add, 6, b as i32));
            bump = b;
        }
    }

    // In-bounds traffic: store then load back, at displacements including zero
    // (which the emitter shortens) and the far end of the arena.
    let room = bytes as i64 - bump;
    let n_pairs = 1 + rng.below(4) as usize;
    for _ in 0..n_pairs {
        // Aligned, in bounds, and inside `off16`.
        let max_slot = ((room - 8).max(0) / 8) as u32;
        let off = if rng.chance(25) {
            0i16
        } else {
            (rng.below(max_slot + 1) * 8) as i16
        };
        let v = rng.imm();
        prog.push(Decoded::Store {
            size: Size::Dw,
            dst: r(6),
            off,
            src: Source::Imm(v),
        });
        let dst = rng.reg();
        if dst != 6 {
            prog.push(Decoded::Load {
                size: Size::Dw,
                sign_extend: false,
                dst: r(dst),
                src: r(6),
                off,
            });
        }
    }

    // …and, sometimes, one access the arena cannot satisfy. Last, so
    // everything above still executed identically on both paths before the
    // trap. The verifier accepts these — it bounds a displacement against a
    // fixed 4 GiB window, not against this program's extent — so reaching the
    // runtime bound is the premise and not an accident.
    if rng.chance(45) {
        let off = [4096i16, 8192, 16384, 32760][rng.below(4) as usize];
        // Only actually out of bounds if it clears the arena; otherwise it is
        // just another in-bounds access, which is fine too.
        prog.push(Decoded::Store {
            size: Size::Dw,
            dst: r(6),
            off,
            src: Source::Imm(0xBAD),
        });
    }

    prog.push(super::mov_reg(
        0,
        [0u8, 1, 2, 3, 4, 5, 7, 8, 9][rng.below(9) as usize],
    ));
    prog.push(Decoded::Exit);
    prog
}

/// Load `items` against an arena group this run already owns.
///
/// Deliberately *not* [`super::arena_prog`], which reserves a fresh
/// [`ArenaSlot`](narf_memory::bpf_arena::ArenaSlot) per call. Slot VA is never
/// recycled — `ArenaSlot::reserve` bumps a cursor over a 64-slot window and
/// `ArenaSlot` has no `Drop`, on purpose, so that a stale TLB entry on a peer
/// CPU can never alias a later mapping. A per-iteration group therefore burns a
/// slot per iteration and exhausts the window; the first version of this test
/// did exactly that at 48 iterations and took every arena smoke that ran after
/// it down with it. Three groups for the whole run, shared by `Arc`, is the fix.
fn load_against(
    group: &alloc::sync::Arc<crate::arena::ArenaGroup>,
    items: &[Decoded],
) -> Option<alloc::sync::Arc<crate::prog::BpfProg>> {
    crate::prog::BpfProg::load_with_arena(
        super::load_cap(),
        crate::prog::LoadRequest {
            name: alloc::string::String::from("fuzz_arena"),
            insns: asm(items),
            context: Context::Atomic,
            maps: Vec::new(),
        },
        Some(alloc::sync::Arc::clone(group)),
    )
    .ok()
}

fn smoke_bpf_jit_fuzz_generated_arena_programs_match_the_interpreter() -> TestResult {
    // The one lowering with no bounds check in it: an arena access is a bare
    // dereference plus an exception-table entry, and the *only* thing that
    // makes an out-of-bounds one non-fatal is the fixup. Comparing trap
    // discriminants is what rules out the tempting-but-wrong fixup — Linux's
    // `ex_handler_bpf` zeroes the destination and resumes, which would make a
    // wild arena access *return a value* natively and trap interpreted.
    if !narf_bpf_jit::has_backend() {
        return TestResult::Skip(NO_BACKEND);
    }
    let base = cmdline_seed()
        .unwrap_or(BASE_SEED)
        .wrapping_mul(0x9E37_79B9_7F4A_7C15);
    let iters = cmdline_iters().map_or(DEFAULT_ARENA_ITERS, |n| n / 2 + 1);
    let mut generated = 0u32;
    let mut verified = 0u32;
    let mut compiled = 0u32;
    let mut trapped = 0u32;
    let mut returned = 0u32;

    // Three arenas for the whole run — see `load_against`. Different sizes so
    // "the far end of the arena" is a different address in each, and so the
    // out-of-bounds displacements land in bounds for the large one and past the
    // end of the small one.
    let cap = crate::arena::kernel_arena_cap();
    let mut groups: Vec<(alloc::sync::Arc<crate::arena::ArenaGroup>, usize)> = Vec::new();
    for pages in [1usize, 2, 4] {
        match crate::arena::ArenaGroup::with_one(cap, pages) {
            Ok(g) => groups.push((alloc::sync::Arc::new(g), pages)),
            Err(_) => return TestResult::Fail("could not reserve an arena for the fuzzer"),
        }
    }

    let trace = cmdline_trace();
    for k in 0..iters {
        let seed = seed_for(base, k);
        if trace {
            note!("bpf-fuzz: trying arena seed={seed:#018x}");
        }
        let (group, pages) = &groups[(k as usize) % groups.len()];
        let items = generate_arena(seed, *pages);
        generated += 1;
        let Some(p) = load_against(group, &items) else {
            continue;
        };
        verified += 1;
        match diff_run(&p, [0; 4]) {
            Ok(()) => compiled += 1,
            Err(e) if e == NO_BACKEND => return TestResult::Skip(NO_BACKEND),
            Err(e) if e == NOT_COMPILED => {}
            Err(e) => {
                note!("bpf-fuzz: ARENA DIVERGENCE base={base:#018x} seed={seed:#018x} — {e}");
                note!("bpf-fuzz: replay by adding ({seed:#018x}, {pages}) to PINNED_ARENA_SEEDS");
                for (i, d) in items.iter().enumerate() {
                    note!("bpf-fuzz:   [{i:3}] {d:?}");
                }
                return TestResult::Fail("a generated arena program diverged");
            }
        }
        match p.run_atomic([0; 4], 4) {
            Some(Outcome::Trapped(_)) => trapped += 1,
            Some(Outcome::Returned(_)) => returned += 1,
            None => {}
        }
    }

    note!(
        "bpf-fuzz: arena base={base:#018x} n={generated} verified={verified} compiled={compiled} ({}% of verified, {}% of generated) returned={returned} trapped={trapped}",
        pct(compiled, verified),
        pct(compiled, generated)
    );
    if generated == 0 {
        return TestResult::Fail("no arena programs were generated");
    }
    // The floor is on compiled-out-of-*verified*, because those are two
    // different claims: a program the verifier refuses says nothing about the
    // backends, while a verified program that falls back is a subject the
    // comparison cannot use. Both numbers are printed, so a generator drifting
    // into shapes the verifier rejects is visible rather than absorbed.
    if pct(compiled, verified) < MIN_COMPILED_PCT {
        return TestResult::Fail("too few verified arena programs compiled");
    }
    if pct(verified, generated) < MIN_VERIFIED_PCT {
        return TestResult::Fail("too few generated arena programs verified");
    }
    // Both verdicts must occur, or the sweep is only testing one of the two
    // things it exists to test.
    if trapped == 0 {
        return TestResult::Fail("no generated arena program reached the runtime bound");
    }
    if returned == 0 {
        return TestResult::Fail("no generated arena program completed");
    }
    TestResult::Pass
}
kernel_test_in!(
    "bpf/fuzz",
    smoke_bpf_jit_fuzz_generated_arena_programs_match_the_interpreter
);

/// Arena seeds to replay every boot, each with the arena size it was found on.
///
/// The arena counterpart of [`PINNED_SEEDS`]. Separate because an arena
/// program's in-bounds displacements are chosen against a page count, so a seed
/// on its own does not reproduce the program.
const PINNED_ARENA_SEEDS: &[(u64, usize)] = &[
    // Not divergences — two arbitrary seeds, so the replay path is exercised on
    // a tree where the arena fuzzer has found nothing.
    (0x0000_0000_0000_0002, 4),
    (0xD239_2D50_5322_34FF, 4),
];

fn smoke_bpf_jit_fuzz_replays_pinned_arena_seeds() -> TestResult {
    if !narf_bpf_jit::has_backend() {
        return TestResult::Skip(NO_BACKEND);
    }
    // One group for the whole test, at the largest size any pinned entry uses,
    // because arena slot VA is never recycled — see `load_against`. A seed
    // pinned against a smaller arena is replayed against this one; the
    // generator was given that seed's page count, so the *program* is identical
    // and only the arena behind it is larger, which changes nothing about what
    // the two backends do with it.
    let cap = crate::arena::kernel_arena_cap();
    let widest = PINNED_ARENA_SEEDS.iter().map(|e| e.1).max().unwrap_or(1);
    let group = match crate::arena::ArenaGroup::with_one(cap, widest) {
        Ok(g) => alloc::sync::Arc::new(g),
        Err(_) => return TestResult::Fail("could not reserve an arena for the replay"),
    };
    let mut compiled = 0u32;
    for &(seed, pages) in PINNED_ARENA_SEEDS {
        let items = generate_arena(seed, pages);
        let Some(p) = load_against(&group, &items) else {
            note!("bpf-fuzz: pinned arena seed {seed:#018x} no longer verifies");
            return TestResult::Fail("a pinned arena seed no longer produces a valid program");
        };
        match diff_run(&p, [0; 4]) {
            Ok(()) => compiled += 1,
            Err(e) if e == NO_BACKEND => return TestResult::Skip(NO_BACKEND),
            Err(e) => {
                note!("bpf-fuzz: pinned arena seed {seed:#018x} diverged — {e}");
                for (i, d) in items.iter().enumerate() {
                    note!("bpf-fuzz:   [{i:3}] {d:?}");
                }
                return TestResult::Fail("a pinned arena seed diverged");
            }
        }
    }
    if compiled == 0 {
        return TestResult::Fail("no pinned arena seed compiled, so nothing was replayed");
    }
    TestResult::Pass
}
kernel_test_in!("bpf/fuzz", smoke_bpf_jit_fuzz_replays_pinned_arena_seeds);

// ── the repertoire boundary ─────────────────────────────────────────

fn smoke_bpf_jit_fuzz_unlowered_shapes_still_fall_back() -> TestResult {
    // The generator's repertoire is "what both backends lower", which is a
    // claim about *other* files. This is that claim, executed.
    //
    // Each program below is well-formed and contains exactly one shape neither
    // backend emits, so it must load and must *not* compile. When somebody
    // teaches a backend one of these, this test goes red at that entry — which
    // is the signal to add the shape to the fuzzer's repertoire rather than to
    // leave it silently uncovered. Deleting the entry to get green is the one
    // wrong move, and saying so here is cheaper than finding out later.
    if !narf_bpf_jit::has_backend() {
        return TestResult::Skip(NO_BACKEND);
    }
    let cases: [(&str, Vec<Decoded>); 6] = [
        (
            "div",
            alloc::vec![
                super::mov_imm(0, 100),
                super::mov_imm(1, 7),
                Decoded::Div {
                    wide: true,
                    signed: false,
                    dst: r(0),
                    src: Source::Reg(r(1)),
                },
                Decoded::Exit,
            ],
        ),
        (
            "mod",
            alloc::vec![
                super::mov_imm(0, 100),
                Decoded::Mod {
                    wide: true,
                    signed: false,
                    dst: r(0),
                    src: Source::Imm(7),
                },
                Decoded::Exit,
            ],
        ),
        (
            "byte-swap",
            alloc::vec![
                super::mov_imm(0, 0x1234),
                Decoded::End {
                    dst: r(0),
                    order: narf_bpf_isa::ByteOrder::Little,
                    width: 32,
                },
                Decoded::Exit,
            ],
        ),
        (
            "narrow stack load",
            alloc::vec![
                super::st_imm(10, -8, 0x5A5A),
                Decoded::Load {
                    size: Size::W,
                    sign_extend: false,
                    dst: r(0),
                    src: r(10),
                    off: -8,
                },
                Decoded::Exit,
            ],
        ),
        (
            "sign-extending load",
            alloc::vec![
                super::st_imm(10, -8, -1),
                Decoded::Load {
                    size: Size::W,
                    sign_extend: true,
                    dst: r(0),
                    src: r(10),
                    off: -8,
                },
                Decoded::Exit,
            ],
        ),
        (
            "MOVSX",
            alloc::vec![
                super::mov_imm(0, -1),
                Decoded::Mov {
                    wide: true,
                    dst: r(0),
                    src: Source::Reg(r(0)),
                    sign_extend: Some(8),
                },
                Decoded::Exit,
            ],
        ),
    ];
    for (what, items) in cases {
        let Ok(p) = load("unlowered", asm(&items), Context::Atomic) else {
            // A shape the *verifier* refuses is not evidence about the
            // backends, and silently skipping it would hollow this out.
            note!("bpf-fuzz: the verifier rejected the '{what}' probe");
            return TestResult::Fail("an unlowered-shape probe no longer verifies");
        };
        if p.is_jited() {
            note!("bpf-fuzz: a backend now lowers '{what}' — add it to the fuzzer's repertoire");
            return TestResult::Fail(
                "a backend gained a shape the fuzzer does not generate — extend the repertoire",
            );
        }
    }
    TestResult::Pass
}
kernel_test_in!(
    "bpf/fuzz",
    smoke_bpf_jit_fuzz_unlowered_shapes_still_fall_back
);
