//! Generated differential fuzzing of the BPF JIT against the interpreter.
//!
//! Every other JIT-vs-interpreter comparison in the tree is a *hand-written*
//! case: someone thought of a shape and wrote it down. That finds the bugs
//! somebody suspected. This finds the rest — random well-formed programs,
//! loaded, compiled, and run both ways, compared through the one comparison
//! [`super::diff_run`] implements (results, trap *discriminants*, and the
//! `is_jited()` assertion that stops a fallen-back subject comparing the
//! interpreter with itself).
//!
//! ## Well-formed by construction, not by rejection sampling
//!
//! A generator that emits random 64-bit words tests the verifier's rejection
//! path and nothing else — it would produce a compiled subject roughly never.
//! This one is built the other way round: every invariant the verifier checks
//! is maintained *while generating*, so the program is well-formed before it is
//! ever handed to `verify`.
//!
//! * **No uninitialised reads.** A prologue writes every one of R0..R9 before
//!   the body starts, and each kfunc call is immediately followed by a re-init
//!   of R1..R5 — the registers the BPF ABI declares caller-saved. Any point the
//!   generator is willing to *branch to* therefore has all ten registers live.
//! * **No writes to R10**, and R10 is never read except as the base of a stack
//!   access, so no scalar can become a pointer by accident.
//! * **Stack accesses are pre-filled.** Every offset the body can load from is
//!   written by the prologue, so a load is always in-bounds *and* reads a value
//!   this run wrote. That second half is what makes the comparison sound at
//!   all: the two runs happen back to back on the same program, so a program
//!   whose output depended on residue from the previous run would diverge for
//!   reasons that are not a JIT bug.
//! * **Context reads happen first**, while R1 still holds the context pointer.
//! * **Branch targets are patched after layout**, from a list of indices the
//!   generator recorded as safe, so a target is always in range and always a
//!   point where the register invariant holds.
//! * **Dead calls are neutralised.** The verifier's fixpoint does not analyse
//!   unreachable code, so a `call` a jump made unreachable has no resolved call
//!   site and the whole program falls back. A reachability pass rewrites those
//!   to a move — see [`neutralise_dead_calls`].
//!
//! The instruction *repertoire* is deliberately exactly what the backends
//! lower: a shape neither backend emits (`div`, `mod`, `LD_IMM64`, atomics,
//! byte-swap, sub-doubleword and sign-extending memory access) would make every
//! program containing it fall back, and a fuzzer whose subjects fall back is a
//! fuzzer comparing the interpreter with itself.
//! [`smoke_bpf_jit_fuzz_unlowered_shapes_still_fall_back`] pins that boundary,
//! so extending a backend makes this module's repertoire go stale *loudly*.
//!
//! ## Determinism and replay
//!
//! One seed per program, derived from a base seed by a mixing step, so
//! iteration *k* is reproducible without replaying iterations 0..k. On a
//! divergence the failing seed is printed and the same program can be
//! regenerated by adding the seed to [`PINNED_SEEDS`], which
//! [`smoke_bpf_jit_fuzz_replays_pinned_seeds`] runs on every boot. That test is
//! the permanent home for anything this fuzzer finds.
//!
//! The base seed is a constant, so an unmodified tree fuzzes the *same* corpus
//! every boot — a CI failure is reproducible by definition. `bpf_fuzz_seed=`
//! and `bpf_fuzz_n=` on the kernel cmdline move it off that corpus for a soak
//! run without changing what CI does:
//!
//! ```text
//! XTASK_QEMU_APPEND='bpf_fuzz_n=4000' cargo xtask test --arch=x86_64 \
//!     --subsystem bpf/fuzz
//! ```
//!
//! These register under `bpf/fuzz` rather than `bpf` so that soak is one boot
//! of five tests rather than the whole subsystem. `subsystem_selected` matches
//! on `/` boundaries, so `--subsystem bpf` still picks them up and the default
//! suite is unchanged.
//!
//! `bpf_fuzz_trace` prints each seed *before* its program runs. That is for the
//! one failure class a differential cannot report at all: a miscompile that
//! corrupts control flow rather than a value takes the kernel down inside the
//! native run, so nothing is left to compare and nothing is printed afterwards.
//! Dropping the aarch64 `x30` save does exactly that — the mutation is caught,
//! in that the suite dies, but only the trace says on which seed.

