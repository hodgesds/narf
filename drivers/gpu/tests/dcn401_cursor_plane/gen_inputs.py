#!/usr/bin/env python3
"""Inputs for check.sh: DRM cursor planes as amdgpu_dm checks them on
DCN 4.0.1 (ARGB8888 framebuffers, their pitch and tiling, the plane's
source and CRTC size). See harness.c for the format."""

ONE = 1 << 16

# GFX12_SWIZZLE_MODE 0 (linear) with other tiling bits (DCC block size,
# SCANOUT), then each GFX12 swizzle mode.
TILINGS = [0, 1 << 3, 1 << 63, 1, 2, 3, 4, 3 | (1 << 3)]


def cursor(w, h, pitch, mods, tiling, src, crtc):
    return (w, h, pitch, mods, tiling) + tuple(src) + tuple(crtc)


def lines():
    out = []
    # Sizes around max_cursor_size, every pitch rule and the tiling.
    for w in (1, 16, 32, 63, 64, 65, 128, 256):
        for h in (1, 24, 64, 65):
            for pitch in sorted({w * 4, 256, 512, 1024, 252, 260}):
                for mods, tiling in [(1, 0)] + [(0, t) for t in TILINGS]:
                    src = (0, 0, w * ONE, h * ONE)
                    out.append(cursor(w, h, pitch, mods, tiling, src, (w, h)))
    # Cropping, fractions and scaling on 64-wide cursors.
    for h in (1, 48, 64):
        whole = (0, 0, 64 * ONE, h * ONE)
        for src in [
            whole,
            (ONE, 0, 64 * ONE, h * ONE),
            (0, ONE, 64 * ONE, h * ONE),
            (0x8000, 0, 64 * ONE, h * ONE),
            (0, 1, 64 * ONE, h * ONE),
            (0, 0, 64 * ONE + 1, h * ONE),
            (0, 0, 64 * ONE - 1, h * ONE),
            (0, 0, 63 * ONE, h * ONE),
            (0, 0, 64 * ONE, h * ONE + 0x8000),
            (0, 0, 64 * ONE, (h - 1) * ONE if h > 1 else 0),
            (0, 0, 32 * ONE, (h // 2 or 1) * ONE),
        ]:
            for crtc in [(64, h), (128, h), (64, 2 * h), (32, h), (64, h - 1), (63, h),
                         (128, 2 * h), (0, 0)]:
                for mods, tiling in [(1, 0), (0, 0), (0, 3)]:
                    out.append(cursor(64, h, 256, mods, tiling, src, crtc))
    return out


print("# Generated by gen_inputs.py: DCN 4.0.1 cursor planes; see harness.c.")
for line in lines():
    print(" ".join(str(v) for v in line))
