/* Native DCN401 HDR/VSC info-packet register contract for the HPO DP stream
 * encoder (dcn31_hpo_dp_stream_enc_update_dp_info_packets through the
 * stream's VPG, MSA7's MISC1 lane) and the HPO FRL stream encoder's DRM
 * InfoFrame (hpo_enc401_update_hdmi_info_packet, packet 4), checked against
 * Linux headers.
 * cc -Wall -Wextra -Werror -I/usr/src/linux/drivers/gpu/drm/amd/include \
 *    drivers/gpu/tests/dcn401_hdr/registers.c -o /tmp/narf-dcn401-hdr-regs
 */
#include "asic_reg/dcn/dcn_4_1_0_offset.h"
#include "asic_reg/dcn/dcn_4_1_0_sh_mask.h"
#define EQ(a,b) _Static_assert((unsigned)(a) == (unsigned)(b), #a)
#define REG(a,b,i) EQ(reg##a,b); EQ(reg##a##_BASE_IDX,i)
/* amdgpu_dcn401_uhbr_video.rs: stride 0xd4; the stream's VPG is VPG n+5. */
#define HPO(n,v) \
 REG(DP_SYM32_ENC##n##_DP_SYM32_ENC_VID_MSA7,(0x3669)+(n)*0xd4,2); \
 REG(DP_SYM32_ENC##n##_DP_SYM32_ENC_SDP_GSP_CONTROL0,(0x366c)+(n)*0xd4,2); \
 REG(DP_SYM32_ENC##n##_DP_SYM32_ENC_SDP_GSP_CONTROL2,(0x366e)+(n)*0xd4,2); \
 REG(DP_SYM32_ENC##n##_DP_SYM32_ENC_SDP_GSP_CONTROL3,(0x366f)+(n)*0xd4,2); \
 REG(DP_SYM32_ENC##n##_DP_SYM32_ENC_SDP_GSP_CONTROL5,(0x3671)+(n)*0xd4,2); \
 REG(DP_SYM32_ENC##n##_DP_SYM32_ENC_SDP_CONTROL,(0x367b)+(n)*0xd4,2); \
 REG(VPG##v##_VPG_GENERIC_PACKET_ACCESS_CTRL,(0x3651)+(n)*0xd4,2); \
 REG(VPG##v##_VPG_GENERIC_PACKET_DATA,(0x3652)+(n)*0xd4,2); \
 REG(VPG##v##_VPG_GSP_IMMEDIATE_UPDATE_CTRL,(0x3654)+(n)*0xd4,2); \
 REG(VPG##v##_VPG_GENERIC_STATUS,(0x3655)+(n)*0xd4,2); \
 REG(VPG##v##_VPG_MEM_PWR,(0x3656)+(n)*0xd4,2)
HPO(0,5); HPO(1,6); HPO(2,7); HPO(3,8);
/* GSP_VIDEO_CONTINUOUS_TRANSMISSION_ENABLE in every GSP control the packets use. */
EQ(DP_SYM32_ENC0_DP_SYM32_ENC_SDP_GSP_CONTROL0__GSP_VIDEO_CONTINUOUS_TRANSMISSION_ENABLE_MASK,1);
EQ(DP_SYM32_ENC0_DP_SYM32_ENC_SDP_GSP_CONTROL2__GSP_VIDEO_CONTINUOUS_TRANSMISSION_ENABLE_MASK,1);
EQ(DP_SYM32_ENC0_DP_SYM32_ENC_SDP_GSP_CONTROL3__GSP_VIDEO_CONTINUOUS_TRANSMISSION_ENABLE_MASK,1);
EQ(DP_SYM32_ENC0_DP_SYM32_ENC_SDP_GSP_CONTROL5__GSP_VIDEO_CONTINUOUS_TRANSMISSION_ENABLE_MASK,1);
EQ(DP_SYM32_ENC0_DP_SYM32_ENC_SDP_CONTROL__SDP_STREAM_ENABLE_MASK,1);
/* MSA7: MSA_DATA_LANE_3 (MISC1) is the top byte. */
EQ(DP_SYM32_ENC0_DP_SYM32_ENC_VID_MSA7__MSA_DATA_MASK,0xffffffff);
/* vpg3_update_generic_info_packet. */
EQ(VPG5_VPG_GENERIC_PACKET_ACCESS_CTRL__VPG_GENERIC_DATA_INDEX_MASK,0xff);
EQ(VPG5_VPG_GENERIC_STATUS__VPG_GENERIC_CONFLICT_OCCURED_MASK,2);
EQ(VPG5_VPG_GENERIC_STATUS__VPG_GENERIC_CONFLICT_CLR_MASK,0x10);
EQ(VPG5_VPG_GSP_IMMEDIATE_UPDATE_CTRL__VPG_GENERIC0_IMMEDIATE_UPDATE_MASK,1u << 0);
EQ(VPG5_VPG_GSP_IMMEDIATE_UPDATE_CTRL__VPG_GENERIC3_IMMEDIATE_UPDATE_MASK,1u << 3);
/* HPO FRL: generic packet 4 (the DRM InfoFrame) SEND/CONT and its line. */
REG(HDMI_TB_ENC_GENERIC_PACKET_CONTROL0,0x8e6,3);
REG(HDMI_TB_ENC_GENERIC_PACKET4_5_LINE,0x8eb,3);
EQ(HDMI_TB_ENC_GENERIC_PACKET_CONTROL0__HDMI_GENERIC4_SEND_MASK,1u << 16);
EQ(HDMI_TB_ENC_GENERIC_PACKET_CONTROL0__HDMI_GENERIC4_CONT_MASK,2u << 16);
EQ(HDMI_TB_ENC_GENERIC_PACKET4_5_LINE__HDMI_GENERIC4_LINE_MASK,0x7fff);
REG(VPG4_VPG_GSP_IMMEDIATE_UPDATE_CTRL,0x934,3);
EQ(VPG4_VPG_GSP_IMMEDIATE_UPDATE_CTRL__VPG_GENERIC4_IMMEDIATE_UPDATE_MASK,1u << 4);
int main(void) { return 0; }
