#!/usr/bin/env bash
# Verify drivers/gpu/tests/dcn401_hdr/vectors.txt against Linux's HDR and
# colorimetry packing: drivers/video/hdmi.c (DRM InfoFrame packer),
# drm_hdmi_helper.c (drm_hdmi_infoframe_set_hdr_metadata), drm_edid.c (HDR
# static metadata block and CTA data block bounds), amdgpu_dm_connector.c
# (amdgpu_dm_fill_hdr_info_packet, amdgpu_dm_get_output_color_space),
# dc_resource.c (set_avi_info_frame's colorimetry and quantization),
# dcn401_dio_stream_encoder.c (DP MSA MISC0/MISC1), dcn31_hpo_dp_stream_encoder.c
# (the 128b/132b stream's MISC0/MISC1) and info_packet.c
# (mod_build_vsc_infopacket). The functions are cut verbatim out of the Linux
# tree by name (or, inside the two big dc functions, between fixed marker
# lines) and compiled against the stub types in harness.c, so the reference
# always is the tree's own text.
#   drivers/gpu/tests/dcn401_hdr/check.sh [linux-tree]
#   drivers/gpu/tests/dcn401_hdr/check.sh --generate [linux-tree] > vectors.txt
# amdgpu_hdr.rs must produce Linux's output for every line.
set -euo pipefail
here=$(CDPATH= cd -- "$(dirname "$0")" && pwd)
generate=0
if [ "${1:-}" = --generate ]; then
	generate=1
	shift
fi
linux=${1:-/usr/src/linux}
d=$linux/drivers/gpu/drm/amd/display
drm=$linux/drivers/gpu/drm
work=$(mktemp -d)
trap 'rm -rf -- "$work"' EXIT

# A function definition at column 0 (its return type may be on the line
# before), through its closing brace.
fn() {
	awk -v n="$2" '
		!p && ($0 ~ "^" n "\\(" || $0 ~ "^[A-Za-z_][^;=]*[ *]" n "\\(") {
			if ($0 ~ "^" n "\\(") print prev
			p = 1
		}
		p { print }
		p && /^}/ { exit }
		{ prev = $0 }' "$1"
}
# A type definition starting with the line "$2", through "};".
ty() {
	awk -v s="$2" '!p && index($0, s) == 1 { p = 1 } p { print } p && /^}/ { exit }' "$1"
}
# The lines from the first containing "$2" up to (not including) the next
# containing "$3".
between() {
	awk -v s="$2" -v e="$3" '!p && index($0, s) { p = 1 } p && index($0, e) { exit } p { print }' "$1"
}
# The lines from the first containing "$2" through the next containing "$3".
through() {
	awk -v s="$2" -v e="$3" '!p && index($0, s) { p = 1 } p { print } p && index($0, e) { exit }' "$1"
}
need() {
	if [ ! -s "$1" ]; then
		echo "extraction failed: $1" >&2
		exit 1
	fi
}

{
	echo "/* Generated by check.sh from $linux; do not edit. */"
	ty "$linux/include/uapi/drm/drm_mode.h" "struct hdr_metadata_infoframe {"
	ty "$linux/include/uapi/drm/drm_mode.h" "struct hdr_output_metadata {"
	ty "$linux/include/drm/drm_connector.h" "enum drm_colorspace {"
	ty "$linux/include/drm/drm_connector.h" "enum drm_hdmi_broadcast_rgb {"
	ty "$drm/drm_edid.c" "struct cea_db {"
	grep -E '^#define (CTA_DB_EXTENDED_TAG|CTA_EXT_DB_HDR_STATIC_METADATA)[[:space:]]' "$drm/drm_edid.c"
	ty "$d/modules/info_packet/info_packet.c" "enum vsc_packet_revision {"
	ty "$d/modules/info_packet/info_packet.c" "enum ColorimetryRGBDP {"
	ty "$d/modules/info_packet/info_packet.c" "enum ColorimetryYCCDP {"
	ty "$d/dc/dc_hw_types.h" "enum dc_color_space {"
	ty "$d/dc/dc_hw_types.h" "enum dc_color_depth {"
	ty "$d/dc/dc_hw_types.h" "enum dc_pixel_encoding {"
	ty "$d/dc/dc_hw_types.h" "enum dc_timing_3d_format {"
	ty "$d/dc/dc_types.h" "enum view_3d_format {"
	ty "$d/dc/dc_types.h" "enum dc_psr_version {"
	ty "$d/dc/dc_types.h" "enum dc_replay_version {"
	ty "$d/dc/dc.h" "enum dc_transfer_func_predefined {"
	ty "$d/modules/inc/mod_shared.h" "enum color_transfer_func {"
	ty "$d/dc/inc/hw/transform.h" "enum colorimetry {"
	ty "$d/dc/inc/hw/transform.h" "enum colorimetry_ext {"
	ty "$d/dc/inc/hw/transform.h" "enum rgb_quantization_range {"
	ty "$d/dc/inc/hw/transform.h" "enum yyc_quantization_range {"
	ty "$d/dc/hpo/dcn31/dcn31_hpo_dp_stream_encoder.c" "enum dp2_pixel_encoding {"
	ty "$d/dc/hpo/dcn31/dcn31_hpo_dp_stream_encoder.c" "enum dp2_uncompressed_component_depth {"
} > "$work/linux_types.h"
{
	echo "/* Generated by check.sh from $linux; do not edit. */"
	fn "$linux/drivers/video/hdmi.c" hdmi_infoframe_checksum
	fn "$linux/drivers/video/hdmi.c" hdmi_infoframe_set_checksum
	fn "$linux/drivers/video/hdmi.c" hdmi_drm_infoframe_init
	fn "$linux/drivers/video/hdmi.c" hdmi_drm_infoframe_pack_only
	fn "$drm/display/drm_hdmi_helper.c" is_eotf_supported
	fn "$drm/display/drm_hdmi_helper.c" drm_hdmi_infoframe_set_hdr_metadata
	fn "$drm/drm_connector.c" drm_connector_atomic_hdr_metadata_equal
	fn "$d/amdgpu_dm/amdgpu_dm_connector.c" amdgpu_dm_fill_hdr_info_packet
	fn "$d/amdgpu_dm/amdgpu_dm_connector.c" amdgpu_dm_get_output_color_space
	fn "$drm/drm_edid.c" cea_db_tag
	fn "$drm/drm_edid.c" cea_db_payload_len
	fn "$drm/drm_edid.c" cea_db_is_extended_tag
	fn "$drm/drm_edid.c" cea_db_is_hdmi_hdr_metadata_block
	fn "$drm/drm_edid.c" cea_db_collection_size
	fn "$drm/drm_edid.c" cea_revision
	fn "$drm/drm_edid.c" __cea_db_iter_current_block
	fn "$drm/drm_edid.c" drm_calculate_luminance_range
	fn "$drm/drm_edid.c" eotf_supported
	fn "$drm/drm_edid.c" hdr_metadata_type
	fn "$drm/drm_edid.c" drm_parse_hdr_metadata_block
	fn "$d/modules/info_packet/info_packet.c" set_vsc_packet_colorimetry_data
	fn "$d/modules/info_packet/info_packet.c" mod_build_vsc_infopacket
	echo "static void set_avi_colorimetry(struct avi_info *hdmi_info_out,"
	echo "		struct dc_stream_state *stream, uint32_t pixel_encoding)"
	echo "{"
	echo "	struct { struct dc_stream_state *stream; } pc = { stream }, *pipe_ctx = &pc;"
	echo "	enum dc_color_space color_space = COLOR_SPACE_UNKNOWN;"
	echo "	struct { struct avi_bits bits; } hdmi_info;"
	echo "	memset(&hdmi_info, 0, sizeof(hdmi_info));"
	through "$d/dc/core/dc_resource.c" "color_space = pipe_ctx->stream->output_color_space;" "COLOR_SPACE_SRGB:COLOR_SPACE_YCBCR709;"
	between "$d/dc/core/dc_resource.c" "/* C0, C1 : Colorimetry */" "/* TODO: un-hardcode aspect ratio */"
	through "$d/dc/core/dc_resource.c" "if (stream->qs_bit == 1) {" "hdmi_info.bits.YQ0_YQ1 ="
	echo "	hdmi_info_out->bits = hdmi_info.bits;"
	echo "}"
	echo "static void dp_msa_misc(const struct dc_crtc_timing *crtc_timing,"
	echo "		enum dc_color_space output_color_space,"
	echo "		bool use_vsc_sdp_for_colorimetry, uint32_t current_misc1,"
	echo "		uint32_t *misc0_out, uint32_t *misc1_out)"
	echo "{"
	echo "	uint32_t misc0 = 0, misc1 = 0;"
	echo "	uint8_t colorimetry_bpc;"
	echo "	struct dc_crtc_timing hw_crtc_timing = *crtc_timing;"
	echo "#define REG_READ(r) current_misc1"
	between "$d/dc/dio/dcn401/dcn401_dio_stream_encoder.c" "misc1 = REG_READ(DP_MSA_MISC);" "/* set color depth */"
	between "$d/dc/dio/dcn401/dcn401_dio_stream_encoder.c" "/* set dynamic range and YCbCr range */" "REG_SET(DP_MSA_COLORIMETRY"
	echo "#undef REG_READ"
	echo "	*misc0_out = misc0;"
	echo "	*misc1_out = misc1;"
	echo "}"
	echo "static void hpo_msa_misc(const struct dc_crtc_timing *crtc_timing,"
	echo "		enum dc_color_space output_color_space,"
	echo "		bool use_vsc_sdp_for_colorimetry, uint32_t *misc0_out, uint32_t *misc1_out)"
	echo "{"
	echo "	uint8_t misc0 = 0, misc1 = 0;"
	echo "	enum dp2_pixel_encoding pixel_encoding;"
	echo "	enum dp2_uncompressed_component_depth component_depth;"
	echo "	struct dc_crtc_timing hw_crtc_timing = *crtc_timing;"
	echo "#define REG_UPDATE_3(...) ((void)pixel_encoding, (void)component_depth)"
	between "$d/dc/hpo/dcn31/dcn31_hpo_dp_stream_encoder.c" "/* Pixel Encoding */" "/* calculate from vesa timing parameters"
	echo "#undef REG_UPDATE_3"
	echo "	*misc0_out = misc0;"
	echo "	*misc1_out = misc1;"
	echo "}"
} > "$work/linux_fns.h"
need "$work/linux_types.h"
need "$work/linux_fns.h"
for f in hdmi_drm_infoframe_pack_only amdgpu_dm_fill_hdr_info_packet drm_parse_hdr_metadata_block \
	mod_build_vsc_infopacket amdgpu_dm_get_output_color_space "C0, C1" "qs_bit" "misc0 = colorimetry_bpc" \
	"DP_SYM32_ENC_COMPONENT_DEPTH_10BPC;"; do
	grep -q "$f" "$work/linux_fns.h" || { echo "extraction failed: $f" >&2; exit 1; }
done

cc -O1 -Wall -Wno-unused-function -Wno-unused-variable -Wno-unused-but-set-variable \
	-I"$here/include" -I"$work" -idirafter "$linux/include" "$here/harness.c" -o "$work/hdr"

if [ $generate -eq 1 ]; then
	echo "# Linux HDR / colorimetry reference vectors; see check.sh and harness.c."
	"$work/hdr" --generate
	exit 0
fi

grep -v '^#' "$here/vectors.txt" | sed 's/ = .*//' | "$work/hdr" > "$work/got"
grep -v '^#' "$here/vectors.txt" | sed 's/.* = //' > "$work/want"
if ! diff -q "$work/want" "$work/got" >/dev/null; then
	diff "$work/want" "$work/got" | head -20 >&2
	echo "vectors.txt does not match Linux" >&2
	exit 1
fi
echo "$(wc -l < "$work/want") ok"
