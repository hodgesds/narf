/* Native DCN401 CRTC color contract (amdgpu_dcn401_color.rs and its tests),
 * independent of the Rust MMIO model. Host-only compile:
 * cc -Wall -Wextra -Werror -I/usr/src/linux/drivers/gpu/drm/amd/include \
 *    drivers/gpu/tests/dcn401_color_regs.c -o /tmp/narf-dcn401-color-regs
 */
#include "asic_reg/dcn/dcn_4_1_0_offset.h"
#include "asic_reg/dcn/dcn_4_1_0_sh_mask.h"
#define EQ(a,b) _Static_assert((unsigned)(a) == (unsigned)(b), #a)
#define R(a,b,idx) EQ(reg##a,b); EQ(reg##a##_BASE_IDX,idx)
#define M(r,f) r##__##f##_MASK
#define S(r,f) r##__##f##__SHIFT
/* DPP (bank 2, stride 0x16b): PRE_DEGAM, CM_CONTROL, CM_GAMCOR_CONTROL. */
#define DPP(i) \
 R(CNVC_CFG##i##_PRE_DEGAM, 0xced + 0x16b*(i), 2); \
 R(CM##i##_CM_CONTROL, 0xd67 + 0x16b*(i), 2); \
 R(CM##i##_CM_GAMCOR_CONTROL, 0xd77 + 0x16b*(i), 2)
DPP(0); DPP(1); DPP(2); DPP(3);
EQ(M(CNVC_CFG0_PRE_DEGAM,PRE_DEGAM_MODE)|M(CNVC_CFG0_PRE_DEGAM,PRE_DEGAM_SELECT),0x73);
/* dpp3_set_pre_degam(TRANSFER_FUNCTION_SRGB): mode 1, select 0. */
EQ(1 << S(CNVC_CFG0_PRE_DEGAM,PRE_DEGAM_MODE),1);
EQ(M(CM0_CM_CONTROL,CM_BYPASS),1);
EQ(M(CM0_CM_GAMCOR_CONTROL,CM_GAMCOR_MODE)|M(CM0_CM_GAMCOR_CONTROL,CM_GAMCOR_SELECT)|M(CM0_CM_GAMCOR_CONTROL,CM_GAMCOR_PWL_DISABLE),0xf);
/* MPC (bank 3): MPCC_MEM_PWR_CTRL (stride 0x15), the OGAM block (0x5e),
 * the MCM gamut remap modes (0xb0). */
#define OG(i,n,r) R(MPCC_OGAM##i##_##n, r + 0x5e*(i), 3)
#define MPC(i) \
 R(MPCC##i##_MPCC_MEM_PWR_CTRL, 0xd + 0x15*(i), 3); \
 OG(i,MPCC_OGAM_CONTROL,0x7e); OG(i,MPCC_OGAM_LUT_INDEX,0x7f); \
 OG(i,MPCC_OGAM_LUT_DATA,0x80); OG(i,MPCC_OGAM_LUT_CONTROL,0x81); \
 OG(i,MPCC_OGAM_RAMA_START_CNTL_B,0x82); OG(i,MPCC_OGAM_RAMA_START_CNTL_G,0x83); \
 OG(i,MPCC_OGAM_RAMA_START_CNTL_R,0x84); OG(i,MPCC_OGAM_RAMA_START_SLOPE_CNTL_B,0x85); \
 OG(i,MPCC_OGAM_RAMA_START_SLOPE_CNTL_G,0x86); OG(i,MPCC_OGAM_RAMA_START_SLOPE_CNTL_R,0x87); \
 OG(i,MPCC_OGAM_RAMA_END_CNTL1_B,0x8b); OG(i,MPCC_OGAM_RAMA_END_CNTL2_B,0x8c); \
 OG(i,MPCC_OGAM_RAMA_END_CNTL1_G,0x8d); OG(i,MPCC_OGAM_RAMA_END_CNTL2_G,0x8e); \
 OG(i,MPCC_OGAM_RAMA_END_CNTL1_R,0x8f); OG(i,MPCC_OGAM_RAMA_END_CNTL2_R,0x90); \
 OG(i,MPCC_OGAM_RAMA_REGION_0_1,0x94); OG(i,MPCC_OGAM_RAMA_REGION_32_33,0xa4); \
 OG(i,MPCC_OGAM_RAMB_START_CNTL_B,0xa5); OG(i,MPCC_OGAM_RAMB_START_CNTL_R,0xa7); \
 OG(i,MPCC_OGAM_RAMB_START_SLOPE_CNTL_B,0xa8); OG(i,MPCC_OGAM_RAMB_END_CNTL1_B,0xae); \
 OG(i,MPCC_OGAM_RAMB_END_CNTL2_R,0xb3); OG(i,MPCC_OGAM_RAMB_REGION_0_1,0xb7); \
 OG(i,MPCC_OGAM_RAMB_REGION_32_33,0xc7); \
 OG(i,MPCC_GAMUT_REMAP_COEF_FORMAT,0xc8); OG(i,MPCC_GAMUT_REMAP_MODE,0xc9); \
 OG(i,MPC_GAMUT_REMAP_C11_C12_A,0xca); OG(i,MPC_GAMUT_REMAP_C33_C34_A,0xcf); \
 OG(i,MPC_GAMUT_REMAP_C11_C12_B,0xd0); OG(i,MPC_GAMUT_REMAP_C33_C34_B,0xd5); \
 R(MPCC_MCM##i##_MPCC_MCM_FIRST_GAMUT_REMAP_MODE, 0x4de + 0xb0*(i), 3); \
 R(MPCC_MCM##i##_MPCC_MCM_SECOND_GAMUT_REMAP_MODE, 0x4ec + 0xb0*(i), 3)
MPC(0); MPC(1); MPC(2); MPC(3);
EQ(M(MPCC0_MPCC_MEM_PWR_CTRL,MPCC_OGAM_MEM_PWR_DIS),4);
EQ(M(MPCC0_MPCC_MEM_PWR_CTRL,MPCC_OGAM_MEM_PWR_STATE),0x300);
EQ(M(MPCC_OGAM0_MPCC_OGAM_CONTROL,MPCC_OGAM_MODE)|M(MPCC_OGAM0_MPCC_OGAM_CONTROL,MPCC_OGAM_SELECT)|M(MPCC_OGAM0_MPCC_OGAM_CONTROL,MPCC_OGAM_PWL_DISABLE),0xf);
EQ(M(MPCC_OGAM0_MPCC_OGAM_CONTROL,MPCC_OGAM_SELECT),4);
EQ(M(MPCC_OGAM0_MPCC_OGAM_CONTROL,MPCC_OGAM_MODE_CURRENT),0x180);
EQ(M(MPCC_OGAM0_MPCC_OGAM_CONTROL,MPCC_OGAM_SELECT_CURRENT),0x200);
EQ(M(MPCC_OGAM0_MPCC_OGAM_LUT_CONTROL,MPCC_OGAM_LUT_WRITE_COLOR_MASK)|M(MPCC_OGAM0_MPCC_OGAM_LUT_CONTROL,MPCC_OGAM_LUT_HOST_SEL),0x47);
EQ(S(MPCC_OGAM0_MPCC_OGAM_LUT_CONTROL,MPCC_OGAM_LUT_HOST_SEL),6);
EQ(M(MPCC_OGAM0_MPCC_OGAM_LUT_DATA,MPCC_OGAM_LUT_DATA),0x3ffff);
EQ(M(MPCC_OGAM0_MPCC_GAMUT_REMAP_MODE,MPCC_GAMUT_REMAP_MODE),3);
EQ(M(MPCC_OGAM0_MPCC_GAMUT_REMAP_MODE,MPCC_GAMUT_REMAP_MODE_CURRENT),0x180);
EQ(M(MPCC_OGAM0_MPCC_GAMUT_REMAP_COEF_FORMAT,MPCC_GAMUT_REMAP_COEF_FORMAT),1);
EQ(M(MPCC_MCM0_MPCC_MCM_FIRST_GAMUT_REMAP_MODE,MPCC_MCM_FIRST_GAMUT_REMAP_MODE),3);
EQ(M(MPCC_MCM0_MPCC_MCM_SECOND_GAMUT_REMAP_MODE,MPCC_MCM_SECOND_GAMUT_REMAP_MODE),3);
int main(void) { return 0; }
