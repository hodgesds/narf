/* Native cursor contract, independent of the Rust MMIO model.
 * cc -Wall -Wextra -Werror -I/usr/src/linux/drivers/gpu/drm/amd/include \
 *    drivers/gpu/tests/dcn401_cursor.c -o /tmp/narf-dcn401-cursor
 */
#include "asic_reg/dcn/dcn_4_1_0_offset.h"
#include "asic_reg/dcn/dcn_4_1_0_sh_mask.h"
#define EQ(a,b) _Static_assert((unsigned)(a) == (unsigned)(b), #a)
#define R(a,b,bank) EQ(reg##a,b); EQ(reg##a##_BASE_IDX,bank)
#define M(r,f) r##__##f##_MASK
#define PIPE(i) \
 R(CURSOR0_##i##_CURSOR_CONTROL, 0x679 + 0xdc*(i), 2); \
 R(CURSOR0_##i##_CURSOR_SURFACE_ADDRESS, 0x67a + 0xdc*(i), 2); \
 R(CURSOR0_##i##_CURSOR_SURFACE_ADDRESS_HIGH, 0x67b + 0xdc*(i), 2); \
 R(CURSOR0_##i##_CURSOR_SIZE, 0x67c + 0xdc*(i), 2); \
 R(CURSOR0_##i##_CURSOR_POSITION, 0x67d + 0xdc*(i), 2); \
 R(CURSOR0_##i##_CURSOR_HOT_SPOT, 0x67e + 0xdc*(i), 2); \
 R(CURSOR0_##i##_CURSOR_DST_OFFSET, 0x680 + 0xdc*(i), 2); \
 R(HUBPREQ##i##_CURSOR_SETTINGS, 0x653 + 0xdc*(i), 2); \
 R(CM_CUR##i##_CURSOR0_CONTROL, 0xcf1 + 0x16b*(i), 2); \
 R(CM_CUR##i##_CURSOR0_FP_SCALE_BIAS_G_Y, 0xcf4 + 0x16b*(i), 2); \
 R(CM_CUR##i##_CURSOR0_FP_SCALE_BIAS_RB_CRCB, 0xcf5 + 0x16b*(i), 2); \
 R(CM_CUR##i##_CUR0_MATRIX_MODE, 0xcf6 + 0x16b*(i), 2); \
 R(CUR_VUPDATE_LOCK_SET##i, 0x2c5 + 5*(i), 3)
PIPE(0); PIPE(1); PIPE(2); PIPE(3);
EQ(M(CURSOR0_0_CURSOR_CONTROL,CURSOR_ENABLE),1);
EQ(M(CURSOR0_0_CURSOR_CONTROL,CURSOR_REQ_MODE),4);
/* CURSOR_MODE | 2X_MAGNIFY | PITCH | LINES_PER_CHUNK */
EQ(M(CURSOR0_0_CURSOR_CONTROL,CURSOR_MODE)|M(CURSOR0_0_CURSOR_CONTROL,CURSOR_2X_MAGNIFY)|
   M(CURSOR0_0_CURSOR_CONTROL,CURSOR_PITCH)|M(CURSOR0_0_CURSOR_CONTROL,CURSOR_LINES_PER_CHUNK),0x1f030710);
EQ(CURSOR0_0_CURSOR_CONTROL__CURSOR_MODE__SHIFT,8);
EQ(CURSOR0_0_CURSOR_CONTROL__CURSOR_LINES_PER_CHUNK__SHIFT,24);
EQ(M(CURSOR0_0_CURSOR_SURFACE_ADDRESS_HIGH,CURSOR_SURFACE_ADDRESS_HIGH),0xffff);
EQ(M(CURSOR0_0_CURSOR_SIZE,CURSOR_WIDTH)|M(CURSOR0_0_CURSOR_SIZE,CURSOR_HEIGHT),0x01ff01ff);
EQ(CURSOR0_0_CURSOR_SIZE__CURSOR_WIDTH__SHIFT,16);
EQ(M(CURSOR0_0_CURSOR_POSITION,CURSOR_X_POSITION)|M(CURSOR0_0_CURSOR_POSITION,CURSOR_Y_POSITION),0x3fffffff);
EQ(CURSOR0_0_CURSOR_POSITION__CURSOR_X_POSITION__SHIFT,15);
EQ(M(CURSOR0_0_CURSOR_HOT_SPOT,CURSOR_HOT_SPOT_X)|M(CURSOR0_0_CURSOR_HOT_SPOT,CURSOR_HOT_SPOT_Y),0x00ff00ff);
EQ(CURSOR0_0_CURSOR_HOT_SPOT__CURSOR_HOT_SPOT_X__SHIFT,16);
EQ(M(CURSOR0_0_CURSOR_DST_OFFSET,CURSOR_DST_X_OFFSET),0x3fff);
EQ(M(HUBPREQ0_CURSOR_SETTINGS,CURSOR0_CHUNK_HDL_ADJUST),0x300);
EQ(M(CM_CUR0_CURSOR0_CONTROL,CUR0_ENABLE),1);
EQ(M(CM_CUR0_CURSOR0_CONTROL,CUR0_EXPANSION_MODE)|M(CM_CUR0_CURSOR0_CONTROL,CUR0_ROM_EN)|
   M(CM_CUR0_CURSOR0_CONTROL,CUR0_MODE),0x7a);
EQ(CM_CUR0_CURSOR0_CONTROL__CUR0_MODE__SHIFT,4);
EQ(M(CM_CUR0_CURSOR0_FP_SCALE_BIAS_G_Y,CUR0_FP_SCALE_G_Y),0xffff);
EQ(M(CM_CUR0_CUR0_MATRIX_MODE,CUR0_MATRIX_MODE),3);
EQ(M(CUR_VUPDATE_LOCK_SET0,CUR_VUPDATE_LOCK_SET),1);
int main(void) { return 0; }
