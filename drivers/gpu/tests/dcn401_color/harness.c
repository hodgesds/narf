/* Recorded register writes, in program order. */
static uint32_t writes[64][2];
static int nwrites;

uint32_t generic_reg_set_ex(const struct dc_context *ctx, uint32_t addr,
		uint32_t reg_val, int n, uint8_t shift1, uint32_t mask1,
		uint32_t field_value1, ...)
{
	(void)ctx;
	uint32_t mask = mask1, value = (field_value1 << shift1) & mask1;
	va_list ap;

	va_start(ap, field_value1);
	for (int i = 1; i < n; i++) {
		uint32_t shift = va_arg(ap, uint32_t);
		uint32_t m = va_arg(ap, uint32_t);
		uint32_t v = va_arg(ap, uint32_t);

		mask |= m;
		value |= (v << (uint8_t)shift) & m;
	}
	va_end(ap);
	reg_val = (reg_val & ~mask) | value;
	writes[nwrites][0] = addr;
	writes[nwrites][1] = reg_val;
	nwrites++;
	return reg_val;
}

/* --- amdgpu_dm_color.c, verbatim apart from kernel allocation. --- */
#define MAX_DRM_LUT_VALUE 0xFFFF
#define MAX_COLOR_LUT_ENTRIES 4096
#define MAX_COLOR_LEGACY_LUT_ENTRIES 256
#define SDR_WHITE_LEVEL_INIT_VALUE 80
struct drm_color_lut { uint16_t red, green, blue, reserved; };
/* include/drm/drm_color_mgmt.h, bit_precision <= 16. */
#define DIV_ROUND_CLOSEST(x, d) (((x) + ((d) / 2)) / (d))
static uint32_t drm_color_lut_extract(uint32_t user_input, int bit_precision)
{
	return DIV_ROUND_CLOSEST(user_input * ((1 << bit_precision) - 1),
				 (1 << 16) - 1);
}

static void __drm_lut_to_dc_gamma(const struct drm_color_lut *lut,
				  struct dc_gamma *gamma, bool is_legacy)
{
	uint32_t r, g, b;
	int i;

	if (is_legacy) {
		for (i = 0; i < MAX_COLOR_LEGACY_LUT_ENTRIES; i++) {
			r = drm_color_lut_extract(lut[i].red, 16);
			g = drm_color_lut_extract(lut[i].green, 16);
			b = drm_color_lut_extract(lut[i].blue, 16);

			gamma->entries.red[i] = dc_fixpt_from_int(r);
			gamma->entries.green[i] = dc_fixpt_from_int(g);
			gamma->entries.blue[i] = dc_fixpt_from_int(b);
		}
		return;
	}

	/* else */
	for (i = 0; i < MAX_COLOR_LUT_ENTRIES; i++) {
		r = drm_color_lut_extract(lut[i].red, 16);
		g = drm_color_lut_extract(lut[i].green, 16);
		b = drm_color_lut_extract(lut[i].blue, 16);

		gamma->entries.red[i] = dc_fixpt_from_fraction(r, MAX_DRM_LUT_VALUE);
		gamma->entries.green[i] = dc_fixpt_from_fraction(g, MAX_DRM_LUT_VALUE);
		gamma->entries.blue[i] = dc_fixpt_from_fraction(b, MAX_DRM_LUT_VALUE);
	}
}

static struct fixed31_32 amdgpu_dm_fixpt_from_s3132(uint64_t x)
{
	struct fixed31_32 val;

	/* If negative, convert to 2's complement. */
	if (x & (1ULL << 63))
		x = -(x & ~(1ULL << 63));

	val.value = x;
	return val;
}

static void __drm_ctm_to_dc_matrix(const uint64_t *ctm, struct fixed31_32 *matrix)
{
	int i;

	for (i = 0; i < 12; i++) {
		/* Skip 4th element */
		if (i % 4 == 3) {
			matrix[i] = dc_fixpt_zero;
			continue;
		}

		/* gamut_remap_matrix[i] = ctm[i - floor(i/4)] */
		matrix[i] = amdgpu_dm_fixpt_from_s3132(ctm[i - (i / 4)]);
	}
}

/* amdgpu_dm_check_crtc_color_mgmt: legacy (256) -> __set_legacy_tf on an sRGB
 * out TF; 4096 -> amdgpu_dm_set_atomic_regamma (tf LINEAR) ->
 * __set_output_tf -> mod_color_calculate_degamma_params. */
static bool regamma(struct dc_transfer_func *func,
		    const struct drm_color_lut *lut, uint32_t lut_size)
{
	struct dc_gamma *gamma = calloc(1, sizeof(*gamma));
	struct calculate_buffer cal_buffer = {0};
	bool res;

	cal_buffer.buffer_index = -1;
	gamma->num_entries = lut_size;
	func->sdr_ref_white_level = SDR_WHITE_LEVEL_INIT_VALUE;
	func->type = TF_TYPE_DISTRIBUTED_POINTS;
	if (lut_size == MAX_COLOR_LEGACY_LUT_ENTRIES) {
		func->tf = TRANSFER_FUNCTION_SRGB;
		gamma->type = GAMMA_RGB_256;
		__drm_lut_to_dc_gamma(lut, gamma, true);
		res = mod_color_calculate_regamma_params(func, gamma, true, false,
							 NULL, &cal_buffer);
	} else {
		func->tf = TRANSFER_FUNCTION_LINEAR;
		__drm_lut_to_dc_gamma(lut, gamma, false);
		gamma->type = GAMMA_CUSTOM;
		res = mod_color_calculate_degamma_params(NULL, func, gamma, true);
	}
	free(gamma);
	return res;
}

/* --- mpc401_set_gamut_remap's coefficient conversion. --- */
static int gamut_remap(const struct fixed31_32 *m, uint16_t *hw_matrix)
{
	enum cm_gamut_coef_format coef_format = CM_GAMUT_REMAP_COEF_FORMAT_S2_13;
	struct fixed31_32 abs_max_coef = {0};
	unsigned int i;

	for (i = 0; i < 12; i++) {
		if (dc_fixpt_le(abs_max_coef, dc_fixpt_abs(m[i])))
			abs_max_coef = dc_fixpt_abs(m[i]);
	}

	if (dc_fixpt_le(abs_max_coef, dc_fixpt_from_fraction(S2D13_MAX, DIVIDER)))
		coef_format = CM_GAMUT_REMAP_COEF_FORMAT_S2_13;
	else
		coef_format = CM_GAMUT_REMAP_COEF_FORMAT_S3_12;

	convert_float_matrix(hw_matrix, m, coef_format, 12);
	return coef_format;
}

/* --- The vector LUT generator (mirrored by amdgpu_dcn_color_tests.rs). --- */
static uint64_t rng;
static uint32_t next(void)
{
	/* xorshift64 */
	rng ^= rng << 13;
	rng ^= rng >> 7;
	rng ^= rng << 17;
	return (uint32_t)(rng >> 32);
}

static uint16_t ramp(uint32_t i, uint32_t n)
{
	return (uint16_t)((uint64_t)i * 0xffff / (n - 1));
}

/* Kind: 0 identity, 1 inverted, 2 random monotone, 3 random, 4 doubled
 * and clipped, 5 per-channel identity/inverted/monotone, 6 squares and
 * cubes, 7 Windows-style i * 0xFF00 / (n - 1), 8 identity +-1 noise,
 * 9 mid grey, 10 identity with one channel raised past 0xFF00. */
static void lut(struct drm_color_lut *l, uint32_t n, int kind, uint64_t seed)
{
	uint32_t acc[3] = {0, 0, 0};

	rng = seed * 2 + 1;
	for (uint32_t i = 0; i < n; i++) {
		uint16_t c[3];

		for (int k = 0; k < 3; k++) {
			uint32_t v;
			int kk = kind == 5 ? k : kind;

			switch (kk) {
			case 0: v = ramp(i, n); break;
			case 1: v = 0xffff - ramp(i, n); break;
			case 2:
				acc[k] += next() % (2 * 0x10000 / n + 1);
				v = acc[k] > 0xffff ? 0xffff : acc[k];
				break;
			case 3: v = next() & 0xffff; break;
			case 4:
				v = 2 * ramp(i, n);
				v = v < 0x4000 ? 0 : v - 0x4000;
				v = v > 0xffff ? 0xffff : v;
				break;
			case 6: {
				uint64_t x = i, d = n - 1;

				v = k == 2 ? (uint32_t)(x * x * x * 0xffff / (d * d * d))
					   : (uint32_t)(x * x * 0xffff / (d * d));
				break;
			}
			case 7: v = (uint32_t)((uint64_t)i * 0xff00 / (n - 1)); break;
			case 8: {
				int64_t x = ramp(i, n) + (int64_t)(next() % 3) - 1;

				v = x < 0 ? 0 : x > 0xffff ? 0xffff : (uint32_t)x;
				break;
			}
			case 9: v = 0x8000; break;
			default:
				v = ramp(i, n);
				if (k == 1 && i == n - 1)
					v = 0xff80;
				else if (k == 1)
					v = (uint32_t)((uint64_t)i * 0xff00 / (n - 1));
				break;
			}
			c[k] = (uint16_t)v;
		}
		l[i].red = c[0];
		l[i].green = c[1];
		l[i].blue = c[2];
		l[i].reserved = 0;
	}
}

static uint32_t fnv(uint32_t h, uint32_t w)
{
	for (int b = 0; b < 4; b++) {
		h ^= (w >> (8 * b)) & 0xff;
		h *= 16777619u;
	}
	return h;
}

static void gamma_line(char tag, uint32_t n, int kind, uint64_t seed)
{
	static struct drm_color_lut l[MAX_COLOR_LUT_ENTRIES];
	static struct dc_transfer_func func;
	static struct pwl_params params;
	struct dcn3_xfer_func_reg reg = {0};
	uint32_t h = 2166136261u, num;
	bool eq;

	memset(&func, 0, sizeof(func));
	lut(l, n, kind, seed);
	if (!regamma(&func, l, n) ||
	    !cm3_helper_translate_curve_to_hw_format(NULL, &func, &params, false)) {
		printf("-\n");
		return;
	}
	/* mpc3_ogam_get_reg_field, with distinct fake register numbers. */
#define F(f, r) reg.shifts.f = MPCC_OGAM0_MPCC_OGAM_RAMA_##r##__SHIFT; \
	reg.masks.f = MPCC_OGAM0_MPCC_OGAM_RAMA_##r##_MASK
	F(exp_region0_lut_offset, REGION_0_1__MPCC_OGAM_RAMA_EXP_REGION0_LUT_OFFSET);
	F(exp_region0_num_segments, REGION_0_1__MPCC_OGAM_RAMA_EXP_REGION0_NUM_SEGMENTS);
	F(exp_region1_lut_offset, REGION_0_1__MPCC_OGAM_RAMA_EXP_REGION1_LUT_OFFSET);
	F(exp_region1_num_segments, REGION_0_1__MPCC_OGAM_RAMA_EXP_REGION1_NUM_SEGMENTS);
	F(field_region_end, END_CNTL2_B__MPCC_OGAM_RAMA_EXP_REGION_END_B);
	F(field_region_end_slope, END_CNTL2_B__MPCC_OGAM_RAMA_EXP_REGION_END_SLOPE_B);
	F(field_region_end_base, END_CNTL1_B__MPCC_OGAM_RAMA_EXP_REGION_END_BASE_B);
	F(field_region_linear_slope, START_SLOPE_CNTL_B__MPCC_OGAM_RAMA_EXP_REGION_START_SLOPE_B);
	F(exp_region_start, START_CNTL_B__MPCC_OGAM_RAMA_EXP_REGION_START_B);
	F(exp_resion_start_segment, START_CNTL_B__MPCC_OGAM_RAMA_EXP_REGION_START_SEGMENT_B);
	reg.start_cntl_b = 0; reg.start_cntl_g = 1; reg.start_cntl_r = 2;
	reg.start_slope_cntl_b = 3; reg.start_slope_cntl_g = 4; reg.start_slope_cntl_r = 5;
	reg.start_end_cntl1_b = 6; reg.start_end_cntl1_g = 7; reg.start_end_cntl1_r = 8;
	reg.start_end_cntl2_b = 9; reg.start_end_cntl2_g = 10; reg.start_end_cntl2_r = 11;
	reg.region_start = 12; reg.region_end = 28;
	nwrites = 0;
	cm_helper_program_gamcor_xfer_func(NULL, &params, &reg);
	/* Written B G R per pair; printed in register order. */
	uint32_t word[29];
	for (int i = 0; i < nwrites; i++)
		word[writes[i][0]] = writes[i][1];
	if (nwrites != 29) {
		printf("bad write count %d\n", nwrites);
		return;
	}
	/* mpc3_program_ogam_pwl's LUT_DATA words. */
	num = params.hw_points_num;
	eq = is_rgb_equal(params.rgb_resulted, num);
	for (uint32_t i = 0; i < num; i++)
		h = fnv(h, params.rgb_resulted[i].red_reg & 0x3ffff);
	for (uint32_t i = 0; i < num; i++)
		h = fnv(h, params.rgb_resulted[i].green_reg & 0x3ffff);
	for (uint32_t i = 0; i < num; i++)
		h = fnv(h, params.rgb_resulted[i].blue_reg & 0x3ffff);
	for (int i = 0; i < 29; i++)
		printf("%x ", word[i]);
	printf("%s %u %08x", eq ? "eq" : "ne", num, h);
	if (tag == 'F') {
		for (uint32_t i = 0; i < num; i++)
			printf(" %x", params.rgb_resulted[i].red_reg & 0x3ffff);
		for (uint32_t i = 0; i < num; i++)
			printf(" %x", params.rgb_resulted[i].green_reg & 0x3ffff);
		for (uint32_t i = 0; i < num; i++)
			printf(" %x", params.rgb_resulted[i].blue_reg & 0x3ffff);
	}
	printf("\n");
}

static void ctm_line(const uint64_t *ctm)
{
	struct fixed31_32 m[12];
	uint16_t hw[12];
	int format;

	__drm_ctm_to_dc_matrix(ctm, m);
	format = gamut_remap(m, hw);
	printf("%d", format);
	/* cm_helper_program_color_matrices: C11|C12 << 16 ... C33|C34 << 16. */
	for (int i = 0; i < 6; i++)
		printf(" %x", (uint32_t)hw[2 * i] | (uint32_t)hw[2 * i + 1] << 16);
	printf("\n");
}

int main(void)
{
	char line[1024];

	setup_x_points_distribution();
	while (fgets(line, sizeof(line), stdin)) {
		char tag;
		uint32_t n;
		int kind;
		uint64_t seed, ctm[9];

		if (sscanf(line, "%c %u %d %" SCNu64, &tag, &n, &kind, &seed) == 4 &&
		    (tag == 'G' || tag == 'F')) {
			gamma_line(tag, n, kind, seed);
		} else if (sscanf(line, "C %" SCNx64 " %" SCNx64 " %" SCNx64 " %" SCNx64
				  " %" SCNx64 " %" SCNx64 " %" SCNx64 " %" SCNx64 " %" SCNx64,
				  &ctm[0], &ctm[1], &ctm[2], &ctm[3], &ctm[4], &ctm[5],
				  &ctm[6], &ctm[7], &ctm[8]) == 9) {
			ctm_line(ctm);
		} else {
			printf("?\n");
		}
	}
	return 0;
}
