/* Linux reference for drivers/gpu/src/amdgpu_dcn_color.rs; see check.sh.
 *
 * Linked against Linux's own color_gamma.c, fixpt31_32.c, custom_float.c,
 * conversion.c and dcn30_cm_common.c. amdgpu_dm_color.c drags in all of DRM,
 * so its few CRTC helpers (__drm_lut_to_dc_gamma, amdgpu_dm_fixpt_from_s3132,
 * __drm_ctm_to_dc_matrix, __set_legacy_tf, __set_output_tf's paths) are
 * copied verbatim below, as are mpc401_set_gamut_remap's format choice and
 * cm_helper_program_color_matrices' packing (dcn401_mpc.c and
 * dcn10_cm_common.c, which need the whole DC core). The OGAM register
 * image comes from Linux's cm_helper_program_gamcor_xfer_func itself, with
 * mpc3_ogam_get_reg_field's MPCC_OGAM_RAMA field layout, recorded through
 * generic_reg_set_ex.
 *
 * Input lines, one per vector (stdin):
 *   G <entries> <kind> <seed>     GAMMA_LUT of 256 (legacy) or 4096 entries
 *   F <entries> <kind> <seed>     the same, printing every LUT data word
 *   C <m0> .. <m8>                CTM, nine S31.32 sign-magnitude hex words
 * Output, one line per input:
 *   G/F: "-" when amdgpu_dm would bypass (fewer than two entries never
 *        happen here), else the 29 control words (START_CNTL B G R,
 *        START_SLOPE_CNTL B G R, END_CNTL1 B G R, END_CNTL2 B G R,
 *        REGION_0_1 .. REGION_32_33) in hex, then "eq" or "ne"
 *        (is_rgb_equal), the point count, and FNV-1a 32 over the red, green
 *        then blue LUT data words (each word as four little-endian bytes);
 *        F adds every red, green and blue word.
 *   C:   the coefficient format (0 S2.13, 1 S3.12) then the six
 *        C11_C12 .. C33_C34 words in hex.
 * Every LUT is generated by lut() below, which amdgpu_dcn_color_tests.rs
 * mirrors exactly.
 */
