/* Native DCN401 MPC contract. Host-only compile, not linked into the kernel.
 * cc -Wall -Wextra -Werror -I/usr/src/linux/drivers/gpu/drm/amd/include \
 *    drivers/gpu/tests/dcn401_mpc.c -o /tmp/narf-dcn401-mpc
 */
#include "asic_reg/dcn/dcn_4_1_0_offset.h"
#include "asic_reg/dcn/dcn_4_1_0_sh_mask.h"
#define EQ(a,b) _Static_assert((unsigned)(a) == (unsigned)(b), #a)
#define R(a,b) EQ(reg##a,b); EQ(reg##a##_BASE_IDX,3)
#define MP(i,n,r) R(MPCC##i##_##n, r + 0x15*(i))
#define OG(i,n,r) R(MPCC_OGAM##i##_##n, r + 0x5e*(i))
#define MC(i,n,r) R(MPCC_MCM##i##_##n, r + 0xb0*(i))
#define OUT(i,n,r) R(MPC_OUT##i##_##n, r + 4*(i))
#define PIPE(i) \
 MP(i,MPCC_CONTROL,3); MP(i,MPCC_SM_CONTROL,4); \
 MP(i,MPCC_TOP_GAIN,6); MP(i,MPCC_BOT_GAIN_INSIDE,7); MP(i,MPCC_BOT_GAIN_OUTSIDE,8); \
 MP(i,MPCC_MOVABLE_CM_LOCATION_CONTROL,9); \
 MP(i,MPCC_BG_R_CR,0xa); MP(i,MPCC_BG_G_Y,0xb); MP(i,MPCC_BG_B_CB,0xc); \
 OG(i,MPCC_OGAM_CONTROL,0x7e); OG(i,MPCC_GAMUT_REMAP_MODE,0xc9); \
 MC(i,MPCC_MCM_SHAPER_CONTROL,0x453); MC(i,MPCC_MCM_3DLUT_MODE,0x48a); \
 MC(i,MPCC_MCM_1DLUT_CONTROL,0x493); MC(i,MPCC_MCM_FIRST_GAMUT_REMAP_MODE,0x4de); \
 MC(i,MPCC_MCM_SECOND_GAMUT_REMAP_MODE,0x4ec); \
 R(MPC_OUT##i##_CSC_MODE,0x30b + 0xd*(i)); \
 OUT(i,DENORM_CONTROL,0x2f3); OUT(i,DENORM_CLAMP_G_Y,0x2f4); OUT(i,DENORM_CLAMP_B_CB,0x2f5)
PIPE(0); PIPE(1); PIPE(2); PIPE(3);
#define M(r,f) r##__##f##_MASK
#define S(r,f) r##__##f##__SHIFT
EQ(M(MPCC0_MPCC_CONTROL,MPCC_MODE)|M(MPCC0_MPCC_CONTROL,MPCC_ALPHA_BLND_MODE)|M(MPCC0_MPCC_CONTROL,MPCC_ALPHA_MULTIPLIED_MODE)|M(MPCC0_MPCC_CONTROL,MPCC_BLND_ACTIVE_OVERLAP_ONLY)|M(MPCC0_MPCC_CONTROL,MPCC_BG_BPC)|M(MPCC0_MPCC_CONTROL,MPCC_BOT_GAIN_MODE)|M(MPCC0_MPCC_CONTROL,MPCC_GLOBAL_ALPHA)|M(MPCC0_MPCC_CONTROL,MPCC_GLOBAL_GAIN),0xffff0ff3);
EQ((2 << S(MPCC0_MPCC_CONTROL,MPCC_MODE))|(2 << S(MPCC0_MPCC_CONTROL,MPCC_ALPHA_BLND_MODE))|(4 << S(MPCC0_MPCC_CONTROL,MPCC_BG_BPC))|(0xffU << S(MPCC0_MPCC_CONTROL,MPCC_GLOBAL_ALPHA))|(0xffU << S(MPCC0_MPCC_CONTROL,MPCC_GLOBAL_GAIN)),0xffff0422);
EQ(M(MPCC0_MPCC_SM_CONTROL,MPCC_SM_EN)|M(MPCC0_MPCC_SM_CONTROL,MPCC_SM_MODE)|M(MPCC0_MPCC_SM_CONTROL,MPCC_SM_FRAME_ALT)|M(MPCC0_MPCC_SM_CONTROL,MPCC_SM_FIELD_ALT)|M(MPCC0_MPCC_SM_CONTROL,MPCC_SM_FORCE_NEXT_FRAME_POL)|M(MPCC0_MPCC_SM_CONTROL,MPCC_SM_FORCE_NEXT_TOP_POL),0x3033f);
EQ(M(MPCC0_MPCC_TOP_GAIN,MPCC_TOP_GAIN),0x7ffff);
EQ(M(MPCC0_MPCC_BOT_GAIN_INSIDE,MPCC_BOT_GAIN_INSIDE),0x7ffff);
EQ(M(MPCC0_MPCC_BOT_GAIN_OUTSIDE,MPCC_BOT_GAIN_OUTSIDE),0x7ffff);
EQ(M(MPCC0_MPCC_BG_R_CR,MPCC_BG_R_CR),0xfff);
EQ(M(MPCC0_MPCC_BG_G_Y,MPCC_BG_G_Y),0xfff);
EQ(M(MPCC0_MPCC_BG_B_CB,MPCC_BG_B_CB),0xfff);
#define BYPASS(r,f,c) EQ(M(r,f),3); EQ(M(r,f##_CURRENT),c)
EQ(M(MPCC0_MPCC_MOVABLE_CM_LOCATION_CONTROL,MPCC_MOVABLE_CM_LOCATION_CNTL),1);
EQ(M(MPCC0_MPCC_MOVABLE_CM_LOCATION_CONTROL,MPCC_MOVABLE_CM_LOCATION_CNTL_CURRENT),0x10);
BYPASS(MPCC_OGAM0_MPCC_OGAM_CONTROL,MPCC_OGAM_MODE,0x180);
BYPASS(MPCC_OGAM0_MPCC_GAMUT_REMAP_MODE,MPCC_GAMUT_REMAP_MODE,0x180);
EQ(M(MPCC_MCM0_MPCC_MCM_SHAPER_CONTROL,MPCC_MCM_SHAPER_LUT_MODE),3);
EQ(M(MPCC_MCM0_MPCC_MCM_SHAPER_CONTROL,MPCC_MCM_SHAPER_MODE_CURRENT),0xc);
BYPASS(MPCC_MCM0_MPCC_MCM_3DLUT_MODE,MPCC_MCM_3DLUT_MODE,0x300);
BYPASS(MPCC_MCM0_MPCC_MCM_1DLUT_CONTROL,MPCC_MCM_1DLUT_MODE,0x30);
BYPASS(MPCC_MCM0_MPCC_MCM_FIRST_GAMUT_REMAP_MODE,MPCC_MCM_FIRST_GAMUT_REMAP_MODE,0x180);
BYPASS(MPCC_MCM0_MPCC_MCM_SECOND_GAMUT_REMAP_MODE,MPCC_MCM_SECOND_GAMUT_REMAP_MODE,0x180);
BYPASS(MPC_OUT0_CSC_MODE,MPC_OCSC_MODE,0x180);
EQ(M(MPC_OUT0_DENORM_CONTROL,MPC_OUT_DENORM_MODE),0x7000000);
EQ(S(MPC_OUT0_DENORM_CONTROL,MPC_OUT_DENORM_MODE),24);
EQ(M(MPC_OUT0_DENORM_CONTROL,MPC_OUT_DENORM_CLAMP_MIN_R_CR)|M(MPC_OUT0_DENORM_CONTROL,MPC_OUT_DENORM_CLAMP_MAX_R_CR),0xffffff);
EQ(M(MPC_OUT0_DENORM_CLAMP_G_Y,MPC_OUT_DENORM_CLAMP_MIN_G_Y)|M(MPC_OUT0_DENORM_CLAMP_G_Y,MPC_OUT_DENORM_CLAMP_MAX_G_Y),0xffffff);
EQ(M(MPC_OUT0_DENORM_CLAMP_B_CB,MPC_OUT_DENORM_CLAMP_MIN_B_CB)|M(MPC_OUT0_DENORM_CLAMP_B_CB,MPC_OUT_DENORM_CLAMP_MAX_B_CB),0xffffff);
EQ(S(MPC_OUT0_DENORM_CONTROL,MPC_OUT_DENORM_CLAMP_MAX_R_CR),12);
EQ(S(MPC_OUT0_DENORM_CLAMP_G_Y,MPC_OUT_DENORM_CLAMP_MAX_G_Y),12);
EQ(S(MPC_OUT0_DENORM_CLAMP_B_CB,MPC_OUT_DENORM_CLAMP_MAX_B_CB),12);
int main(void) { return 0; }
