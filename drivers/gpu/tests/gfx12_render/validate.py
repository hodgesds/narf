#!/usr/bin/env python3
"""Compare real Mesa constructors and independently round-trip both GFX12 ISAs."""
import ctypes
import hashlib
import json
import os
from pathlib import Path
import re
import struct
import subprocess
import sys

work, rust = map(Path, sys.argv[1:3])
write_data = sys.argv[3:] == ["--write"]
assert not sys.argv[3:] or write_data, "expected optional --write"
lib = ctypes.CDLL(str(work / 'mesa-build/src/amd/vulkan/libvulkan_radeon.so'))
generate = lib.narf_render_fixture
generate.argtypes = [ctypes.c_char_p, ctypes.c_uint, ctypes.c_uint]
generate.restype = ctypes.c_int
variants = {}
for target in [1200, 1201]:
    for pfp in [2630, 2680]:
        path = work / f'gfx{target}-pfp{pfp}.json'
        assert generate(str(path).encode(), target, pfp) == 0
        variants[target,pfp] = json.loads(path.read_text())
if write_data:
    def array(name, values):
        return 'pub(super) static '+name+': &[u32] = &[\n'+''.join(
            '    '+', '.join(f'0x{x:08x}' for x in values[i:i+8])+',\n'
            for i in range(0,len(values),8))+'];\n'
    baseline = variants[1200,2630]
    generated = ('// SPDX-License-Identifier: MIT\n'
                 '// Generated by tests/gfx12_render from pinned Mesa26.2.4; do not hand-edit.\n'
                 '// Upstream copyright notices and license: tests/gfx12_render/MESA_LICENSE.txt.\n')
    for key in ['ngg','ps','upload']:
        generated += array(key.upper(), baseline[key])
    for target in [1200,1201]:
        generated += array(f'DESCRIPTORS_{target}', variants[target,2630]['descriptors'])
    for (target,pfp), data in variants.items():
        generated += array(f'PM4_{target}_{pfp}', data['pm4'])
    rust.write_text(generated)
    subprocess.run([os.environ.get('RUSTFMT','rustfmt'), '--edition','2021',str(rust)],check=True)
text = rust.read_text()
arrays = {name: [int(x, 16) for x in re.findall(r'0x[0-9a-fA-F]+', body)]
          for name,body in re.findall(r'static (\w+): &\[u32\] = &\[(.*?)\];', text, re.S)}
records = []
for target in [1200, 1201]:
    for pfp in [2630, 2680]:
        path = work / f'gfx{target}-pfp{pfp}.json'
        data = variants[target,pfp]
        assert data['surface_size'] == 16384 and data['row_pitch'] == 256
        assert data['surface_offset'] == 0 and data['swizzle'] == 0
        assert data['pixel_addresses_checked'] == 4096
        assert data['max_se'] == (2 if target == 1200 else 4)
        assert data['ge_size'] == (0x400000 if target == 1200 else 0xa80000)
        assert data['ngg_rsrc1'] == 0xc0002 and data['ngg_rsrc2'] == 0x10006
        assert data['ps_rsrc1'] == 0xc0002 and data['ps_rsrc2'] == 0xc
        for key in ['ngg', 'ps', 'upload']:
            assert data[key] == arrays[key.upper()], f'{target}/{pfp}: {key} mismatch'
        assert data['descriptors'] == arrays[f'DESCRIPTORS_{target}']
        assert data['pm4'] == arrays[f'PM4_{target}_{pfp}']
        # Inspect packet boundaries, not incidental opcode-looking payloads.
        at = 0
        draws = 0
        modern = 0
        while at < len(data['pm4']):
            header = data['pm4'][at]
            assert header >> 30 == 3
            size = ((header >> 16) & 0x3fff) + 2
            op = (header >> 8) & 255
            payload = data['pm4'][at+1:at+size]
            assert op != 0x15, 'compute dispatch is not a rendered draw'
            if op == 0x2d:
                assert payload == [3,2]
                draws += 1
            if op == 0xef:
                assert payload == [0]
                modern += 1
            if op == 0x37:  # the only memory write is the owned upload fence.
                assert payload == [0x40100500,0x2010010,0,0,0]
            if op == 0x50:
                # Actual CP prefetch is DST_NOWHERE, preserving code R|X.
                assert payload[0] == 0x60200000 and payload[2] == payload[4] == 0
                assert payload[1] == payload[3] and payload[1] in [0x2000000,0x2001000]
            at += size
        assert at == len(data['pm4']) and draws == 1 and modern == (pfp >= 2680)
        records.append({'target': target, 'pfp': pfp, 'fixture_sha256': hashlib.sha256(path.read_bytes()).hexdigest()})
        print(f'gfx{target}/PFP{pfp}: actual ACO NGG{len(data["ngg"])}+PS{len(data["ps"])} dwords, '
              f'4096 Addrlib3 pixel addresses, descriptors and {len(data["pm4"])} PM4 dwords match')
    for stage in ['ngg', 'ps']:
        code = arrays[stage.upper()]
        assembly = work / f'{target}-{stage}.s'
        binary = assembly.with_suffix('.bin')
        obj = assembly.with_suffix('.o')
        assembly.write_text('.text\n' + ''.join(f'.long {x:#x}\n' for x in code))
        mc = os.environ.get('LLVM_MC', 'llvm-mc')
        dump = os.environ.get('LLVM_OBJDUMP', 'llvm-objdump')
        copy = os.environ.get('LLVM_OBJCOPY', 'llvm-objcopy')
        subprocess.run([mc, '-triple=amdgcn-amd-amdhsa', f'-mcpu=gfx{target}', '-filetype=obj', str(assembly), '-o', str(obj)], check=True)
        disasm = subprocess.check_output([dump, '-d', f'--mcpu=gfx{target}', '--no-show-raw-insn', str(obj)], text=True)
        assert '<unknown>' not in disasm and 'export ' in disasm
        instructions = [line.split('//')[0].strip() for line in disasm.splitlines() if line.startswith('\t')]
        assembly.write_text('.text\n'+'\n'.join(instructions)+'\n')
        subprocess.run([mc, '-triple=amdgcn-amd-amdhsa', f'-mcpu=gfx{target}', '-filetype=obj', str(assembly), '-o', str(obj)], check=True)
        subprocess.run([copy, '-O', 'binary', '--only-section=.text', str(obj), str(binary)], check=True)
        rebuilt = list(struct.unpack('<' + 'I'*len(code), binary.read_bytes()))
        expected = code.copy()
        # ACO uses VGPR selector0x80 for disabled EXP channels; LLVM's
        # assembler canonicalizes those ignored selectors to0. All enabled
        # channels and every other instruction bit must round-trip exactly.
        for line in disasm.splitlines():
            if line.strip().startswith('export '):
                index = int(re.search(r'//\s*([0-9A-Fa-f]+):', line).group(1),16)//4
                enabled = expected[index] & 15
                mask = sum(255 << (lane*8) for lane in range(4) if enabled & (1<<lane))
                expected[index+1] &= mask
                rebuilt[index+1] &= mask
        assert rebuilt == expected
        (work / f'{target}-{stage}.disasm').write_text(disasm)
        print(f'gfx{target}/{stage}: actual Mesa ISA independently round-trips with LLVM (disabled EXP selectors canonicalized)')
(work / 'fixture-manifest.json').write_text(json.dumps(records, indent=2)+'\n')
