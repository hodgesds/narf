/* GC12.0.0/12.0.1 compute proof contract, checked against Linux 7.3-rc7 headers.
 * Run tests/gfx12_shader/check.sh for both this and the independent LLVM check.
 */
#include "nvd.h"
#include "asic_reg/gc/gc_12_0_0_offset.h"
#include "asic_reg/gc/gc_12_0_0_sh_mask.h"
#define EQ(name, value) _Static_assert((unsigned)(name) == (unsigned)(value), #name)
/* Logical PM4 SH address versus GC12's physical MMIO register index. */
#define SH(reg, addr) EQ((reg + 0x1260) * 4, addr)
EQ(PACKET3_SET_SH_REG_START * 4, 0xb000);
EQ(PACKET3(PACKET3_SET_SH_REG, 3) | 2, 0xc0037602u);
EQ(PACKET3(PACKET3_DISPATCH_DIRECT, 3) | 2, 0xc0031502u);
SH(regCOMPUTE_START_X, 0xb810);
SH(regCOMPUTE_NUM_THREAD_X, 0xb81c);
SH(regCOMPUTE_PERFCOUNT_ENABLE, 0xb82c);
SH(regCOMPUTE_PGM_LO, 0xb830);
SH(regCOMPUTE_PGM_HI, 0xb834);
SH(regCOMPUTE_DISPATCH_PKT_ADDR_LO, 0xb838);
SH(regCOMPUTE_DISPATCH_SCRATCH_BASE_HI, 0xb844);
SH(regCOMPUTE_PGM_RSRC1, 0xb848);
SH(regCOMPUTE_PGM_RSRC2, 0xb84c);
SH(regCOMPUTE_RESOURCE_LIMITS, 0xb854);
SH(regCOMPUTE_STATIC_THREAD_MGMT_SE0, 0xb858);
SH(regCOMPUTE_STATIC_THREAD_MGMT_SE1, 0xb85c);
SH(regCOMPUTE_TMPRING_SIZE, 0xb860);
SH(regCOMPUTE_STATIC_THREAD_MGMT_SE2, 0xb864);
SH(regCOMPUTE_STATIC_THREAD_MGMT_SE3, 0xb868);
SH(regCOMPUTE_STATIC_THREAD_MGMT_SE8, 0xb88c);
SH(regCOMPUTE_USER_ACCUM_0, 0xb890);
SH(regCOMPUTE_PGM_RSRC3, 0xb8a0);
SH(regCOMPUTE_STATIC_THREAD_MGMT_SE4, 0xb8ac);
SH(regCOMPUTE_STATIC_THREAD_MGMT_SE5, 0xb8b0);
SH(regCOMPUTE_STATIC_THREAD_MGMT_SE6, 0xb8b4);
SH(regCOMPUTE_STATIC_THREAD_MGMT_SE7, 0xb8b8);
