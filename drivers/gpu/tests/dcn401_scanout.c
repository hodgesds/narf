#define EQ(a,b) _Static_assert((unsigned)(a) == (unsigned)(b), #a)
#define R2(a,b) EQ(reg##a,b); EQ(reg##a##_BASE_IDX,2)
#define R3(a,b) EQ(reg##a,b); EQ(reg##a##_BASE_IDX,3)
#define M(r,f) r##__##f##_MASK
#define PIPE(i) \
 R2(HUBP##i##_DCHUBP_CNTL,0x5f4+0xdc*(i)); R2(HUBP##i##_HUBP_CLK_CNTL,0x5f5+0xdc*(i)); \
 R2(HUBPREQ##i##_DCSURF_PRIMARY_SURFACE_ADDRESS,0x60a+0xdc*(i)); \
 R2(HUBPREQ##i##_DCSURF_PRIMARY_SURFACE_ADDRESS_HIGH,0x60b+0xdc*(i)); \
 R2(HUBPREQ##i##_DCSURF_FLIP_CONTROL,0x613+0xdc*(i)); \
 R2(HUBPREQ##i##_DCSURF_SURFACE_EARLIEST_INUSE,0x61c+0xdc*(i)); \
 R2(HUBPREQ##i##_DCSURF_SURFACE_EARLIEST_INUSE_HIGH,0x61d+0xdc*(i)); \
 R2(CURSOR0_##i##_CURSOR_CONTROL,0x679+0xdc*(i)); \
 R2(DPP_TOP##i##_DPP_CONTROL,0xcc5+0x16b*(i)); \
 R2(DPG##i##_DPG_CONTROL,0x1854+0x5a*(i)); R2(DPG##i##_DPG_STATUS,0x185b+0x5a*(i)); \
 R2(ODM##i##_OPTC_INPUT_GLOBAL_CONTROL,0x1aca+0x10*(i)); \
 R2(OTG##i##_OTG_CONTROL,0x1b43+0x80*(i)); R2(OTG##i##_OTG_STATUS_FRAME_COUNT,0x1b4d+0x80*(i)); \
 R2(OTG##i##_OTG_DOUBLE_BUFFER_CONTROL,0x1b5c+0x80*(i)); \
 R2(OTG##i##_OTG_MASTER_UPDATE_LOCK,0x1b89+0x80*(i)); R2(OTG##i##_OTG_GSL_CONTROL,0x1b8a+0x80*(i)); \
 R2(OTG##i##_OTG_GLOBAL_CONTROL2,0x1b90+0x80*(i)); R2(OTG##i##_OTG_PIPE_UPDATE_STATUS,0x1b9e + 0x80*(i)); \
 R3(MPCC##i##_MPCC_TOP_SEL,0x15*(i)); R3(MPCC##i##_MPCC_BOT_SEL,1+0x15*(i)); \
 R3(MPCC##i##_MPCC_OPP_ID,2+0x15*(i)); R3(MPCC##i##_MPCC_CONTROL,3+0x15*(i)); \
 R3(MPCC##i##_MPCC_UPDATE_LOCK_SEL,5+0x15*(i)); R3(MPCC##i##_MPCC_STATUS,0xe + 0x15*(i)); \
 R3(MPC_OUT##i##_MUX,0x2f2+4*(i))
PIPE(0); PIPE(1); PIPE(2); PIPE(3);
