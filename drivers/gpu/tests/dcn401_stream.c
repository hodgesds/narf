#define EQ(a,b) _Static_assert((unsigned)(a) == (unsigned)(b), #a)
#define REG(a,b) EQ(reg##a,b); EQ(reg##a##_BASE_IDX,2)
#define DIO(i) \
 REG(DIG##i##_DIG_FE_CLK_CNTL,0x2094+0x124*(i)); \
 REG(DIG##i##_DIG_FE_EN_CNTL,0x2095+0x124*(i)); \
 REG(DP##i##_DP_VID_STREAM_CNTL,0x2122+0x124*(i)); \
