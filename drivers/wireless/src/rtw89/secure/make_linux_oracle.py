"""Extract and execute Linux's physical-fuse recognizers; update golden.rs."""
from pathlib import Path
import re, subprocess, sys, tempfile
p = Path(tempfile.mkdtemp(prefix="rtw89-secure-oracle-"))
base = Path(sys.argv[1] if len(sys.argv) > 1 else "/usr/src/linux/drivers/net/wireless/realtek/rtw89")
source = (base / "efuse.c").read_text()
def function(name):
 m=re.search(r'^(?:static\s+)?(?:u8|int)\s+'+name+r'\(',source,re.M);at=m.start();end=source.index('{',at)+1;depth=1
 while depth:
  depth+=(source[end]=='{')-(source[end]=='}');end+=1
 return source[at:end]+'\n'
sec=(base/'core.h').read_text();start=sec.index('struct rtw89_fw_secure {');sec=sec[start:sec.index('\n};',start)+3]
start=source.index('enum rtw89_efuse_mss_dev_type {');enum=source[start:source.index('\n};',start)+3]
defs='\n'.join(line for line in source.splitlines() if line.startswith('#define EFUSE_') or line.startswith('#define OTP_KEY_INFO_NUM'))
arrays='\n'.join(line for line in source.splitlines() if line.startswith('static const u8 otp_key_info_'))+'\n'
c='''/* SPDX-License-Identifier: GPL-2.0 OR BSD-3-Clause */
/* Copyright(c) 2019-2020 Realtek Corporation */
#include <stdint.h>
#include <stdbool.h>
#include <errno.h>
#include <stdio.h>
#include <string.h>
typedef uint8_t u8; typedef uint32_t u32;
#define BIT(x) (1u<<(x))
#define GENMASK(h,l) ((~0u<<(l)) & (~0u>>(31-(h))))
#define u8_get_bits(v,m) (((v)&(m))>>__builtin_ctz(m))
#define rtw89_warn(...) ((void)0)
#define rtw89_debug(...) ((void)0)
#define RTW89_FW_MSS_DEV_TYPE_FWSEC_DEF 15
#define RTW89_FW_MSS_DEV_TYPE_FWSEC_INV 255
#define RTL8852B 1
'''+defs+'\n'+enum+'\n'+sec+'''
struct rtw89_chip_info{int chip_id;};
struct rtw89_dev {struct rtw89_chip_info *chip;struct{struct rtw89_fw_secure sec;}fw;};
static u8 raw[2];
static int rtw89_dump_physical_efuse_map(struct rtw89_dev*d,u8*map,u32 addr,u32 size,bool dav){(void)d;if(addr!=0x5ec||size!=2||dav)return -1;memcpy(map,raw,2);return 0;}
'''+arrays
for name in ['get_mss_dev_type_idx','rtw89_efuse_recognize_mss_info_v1','rtw89_efuse_recognize_mss_index_v0','rtw89_efuse_read_fw_secure_ax']:c+=function(name)
c+='''int main(void){for(int chip=0;chip<2;chip++){struct rtw89_chip_info info={chip};for(unsigned input=0;input<65536;input++){struct rtw89_dev d={0};d.chip=&info;raw[0]=input>>8;raw[1]=input;int result=rtw89_efuse_read_fw_secure_ax(&d);if(result)return 2;struct rtw89_fw_secure*s=&d.fw.sec;u8 out[7]={s->secure_boot,s->can_mss_v0,s->mss_idx,s->can_mss_v1,s->mss_dev_type,s->mss_cust_idx,s->mss_key_num};if(fwrite(out,1,7,stdout)!=7)return 3;}}return 0;}\n'''
(p/'secure_oracle.c').write_text(c);subprocess.run(['cc','-std=gnu11','-O2',str(p/'secure_oracle.c'),'-o',str(p/'secure_oracle')],check=True)
with (p/'secure_oracle.bin').open('wb') as out:subprocess.run([str(p/'secure_oracle')],stdout=out,check=True)

data=(p/'secure_oracle.bin').read_bytes()
assert len(data)==2*65536*7
hash_value=0xcbf29ce484222325
unknown=0
for index in range(0,len(data),7):
 record=bytearray(data[index:index+7])
 if not record[0]:
  record[:]=bytes(7)
  if (index//7)%65536 != 65535: unknown+=1
 else:
  if not record[1]:record[2]=0
  if not record[3]:record[4:]=bytes(3)
 for byte in record:hash_value=((hash_value^byte)*0x100000001b3)&0xffffffffffffffff
output=Path(__file__).with_name('golden.rs')
output.write_text('// Generated by make_linux_oracle.py from actual Linux C recognizers.\n'
                  +f'const LINUX_FUSE_HASH: u64 = 0x{hash_value:016x};\n'
                  +f'const LINUX_UNKNOWN_FUSES: usize = {unknown};\n')
print(output, hex(hash_value), unknown)
