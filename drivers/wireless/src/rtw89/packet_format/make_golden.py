#!/usr/bin/env python3
"""Extract Linux AX descriptor builders; compile them to literal byte fixtures.

Run from any directory. Requires /usr/src/linux and a C compiler. No Rust
implementation is imported. Only inert endian/bitfield shims and the fixture
inputs surround the unmodified source builder/address-info functions.
"""
from pathlib import Path
import re
import subprocess
import tempfile

LINUX = Path('/usr/src/linux/drivers/net/wireless/realtek/rtw89')
CORE = (LINUX / 'core.c').read_text()
PCI = (LINUX / 'pci.c').read_text()
TXRX = (LINUX / 'txrx.h').read_text()
PCIH = (LINUX / 'pci.h').read_text()


def function(source, name):
    start = source.index(name + '(')
    start = source.rfind('\n', 0, start) + 1
    brace = source.index('{', start)
    depth = 1
    end = brace + 1
    while depth:
        depth += (source[end] == '{') - (source[end] == '}')
        end += 1
    return source[start:end]


builders = [function(CORE, 'rtw89_build_txwd_' + suffix) for suffix in
            ['body0', 'body2', 'body3', 'info0', 'info1', 'info2', 'info3', 'info4']]
address = function(PCI, 'rtw89_pci_fill_txaddr_info')
fields = sorted(set(re.findall(r'desc_info->(\w+)', '\n'.join(builders))))
masks = sorted(set(re.findall(r'\bRTW89_\w+', '\n'.join(builders) + address)))
definitions = []
for mask in masks:
    match = re.search(r'^#define\s+' + mask + r'(?=\s|\()(.*)$', TXRX + '\n' + PCIH, re.M)
    if not match:
        raise RuntimeError(mask)
    definitions.append('#define ' + mask + match[1])

program = r'''
#include <stdint.h>
#include <stdbool.h>
#include <stdio.h>
#include <string.h>
typedef uint32_t u32; typedef uint16_t u16; typedef uint8_t u8;
typedef uint32_t __le32; typedef uint16_t __le16; typedef uint64_t dma_addr_t;
#define BIT(n) (1u << (n))
#define GENMASK(h,l) (((~0u) >> (31-(h))) & ((~0u) << (l)))
#define FIELD_PREP(mask,value) (((u32)(value) << __builtin_ctz(mask)) & (mask))
#define cpu_to_le32(v) ((u32)(v))
#define cpu_to_le16(v) ((u16)(v))
#define le16_encode_bits(v,m) ((u16)FIELD_PREP(m,v))
#define upper_32_bits(v) ((u32)((v) >> 32))
struct rtw89_dev { int unused; };
struct rtw89_pci_tx_addr_info_32 { __le16 length,option; __le32 dma; };
'''
program += '\n'.join(definitions) + '\n'
program += 'struct rtw89_tx_desc_info { ' + '; '.join('u32 ' + f for f in fields) + '; };\n'
program += '\n'.join(builders) + '\n' + address + '\n'
program += r'''
static void emit(const unsigned char *p, unsigned n) {
  printf("["); for(unsigned i=0;i<n;i++) printf("%s%u",i?",":"",p[i]); printf("]");
}
int main(void) {
  puts("// Generated by make_golden.py from unmodified Linux C builders.");
  puts("pub(super) const HEADERS: [[u8;64];4] = [");
  for(unsigned i=0;i<4;i++) {
    struct rtw89_tx_desc_info d = {0};
    d.en_wd_info=1; d.ch_dma=i&1?8:0; d.hdr_llc_len=12; d.wd_page=1;
    d.hw_ssn_sel=i&1; d.hw_seq_mode=i&1; d.qsel=i&1?0x12:0;
    d.pkt_size=i<2?100:2304; d.mac_id=0; d.seq=0x123;
    d.use_rate=1; d.dis_data_fb=1; d.report=(i>>1)&1;
    unsigned char output[64]={0}; u32 words[12]={0};
    words[0]=rtw89_build_txwd_body0(&d); words[2]=rtw89_build_txwd_body2(&d);
    words[3]=rtw89_build_txwd_body3(&d);
    words[6]=rtw89_build_txwd_info0(&d); words[7]=rtw89_build_txwd_info1(&d);
    words[8]=rtw89_build_txwd_info2(&d); words[9]=rtw89_build_txwd_info3(&d);
    words[10]=rtw89_build_txwd_info4(&d); memcpy(output,words,sizeof words);
    // Linux txwd_submit: seq0=WD identity|VALID, other WP identities zero.
    u16 sequence=cpu_to_le16((i==3?511:i)|0x8000); memcpy(output+48,&sequence,2);
    u8 count=0; rtw89_pci_fill_txaddr_info(0,output+56,d.pkt_size,
      i>=2?0xf12345000ULL:0x12345000ULL,&count);
    if(count!=1) return 1;
    emit(output,64); puts(",");
  }
  puts("];");
  return 0;
}
'''
with tempfile.TemporaryDirectory(prefix='narf-8852b-txwd-') as directory:
    source = Path(directory) / 'oracle.c'
    binary = Path(directory) / 'oracle'
    source.write_text(program)
    subprocess.run(['cc', '-std=c11', '-Wall', '-Wextra', '-Werror',
                    '-Wno-unused-parameter', str(source), '-o', str(binary)], check=True)
    result = subprocess.check_output([str(binary)], text=True)
Path(__file__).with_name('golden.rs').write_text(result)
