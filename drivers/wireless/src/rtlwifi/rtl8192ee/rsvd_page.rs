//! `rtl8192ee/fw.c::reserved_page_packet` (`TOTAL_RESERVED_PKT_LEN` 1024:
//! eight 128-byte pages — beacon 0..=1, PS-Poll 2, Null 3, probe response
//! 4..=5, QoS-Null 6, BT-QoS-Null 7), generated verbatim from the Linux
//! 7.3-rc4 initializer, and the `rtl92ee_set_fw_rsvdpagepkt(hw, false)`
//! substitutions. Each page after the first carries its own 40-byte TX
//! descriptor in the preceding page's tail exactly as the Linux array lays
//! it out (the host does not rewrite those bytes). The Linux initializer
//! leaves the QoS-Null and BT-QoS-Null pages (6, 7) all zero; Linux still
//! writes their A1/A2/A3, and so does [`pages`].

