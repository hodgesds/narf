/// `rtl92ee_set_fw_rsvdpagepkt(hw, false)` page bodies: beacon A2 (own) /
/// A3 (BSSID); PS-Poll AID `| 0xc000`, BSSID, TA; Null, probe response,
/// QoS-Null and BT-QoS-Null A1 (BSSID), A2 (own), A3 (BSSID). `None` for an
/// AID outside 1..=2007. Linux uploads all 1024 bytes
/// (`rtl_cmd_send_packet`) and then sends [`super::h2c::RSVDPAGE_LOCATION`].
pub fn pages(own: [u8; 6], bssid: [u8; 6], aid: u16) -> Option<[u8; LEN]> {
    if !(1..=2007).contains(&aid) {
        return None;
    }
    let mut bytes = TEMPLATE;
    bytes[10..16].copy_from_slice(&own);
    bytes[16..22].copy_from_slice(&bssid);
    let at = PSPOLL_PG * PAGE;
    bytes[at + 2..at + 4].copy_from_slice(&(aid | 0xc000).to_le_bytes());
    bytes[at + 4..at + 10].copy_from_slice(&bssid);
    bytes[at + 10..at + 16].copy_from_slice(&own);
    for page in [NULL_PG, PROBERSP_PG, QOS_NULL_PG, BT_QOS_NULL_PG] {
        let at = page * PAGE;
        bytes[at + 4..at + 10].copy_from_slice(&bssid);
        bytes[at + 10..at + 16].copy_from_slice(&own);
        bytes[at + 16..at + 22].copy_from_slice(&bssid);
    }
    Some(bytes)
}

