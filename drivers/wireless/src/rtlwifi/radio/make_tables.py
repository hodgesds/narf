"""Import complete factual RTL8188EE table rows from the installed Linux tree."""
from pathlib import Path
import hashlib
import re

base = Path('/usr/src/linux/drivers/net/wireless/realtek/rtlwifi/rtl8188ee')
source = (base / 'table.c').read_text()
names = {
    'RTL8188EEPHY_REG_1TARRAY': ('BB', 2),
    'RTL8188EEPHY_REG_ARRAY_PG': ('POWER_GROUPS', 3),
    'RTL8188EE_RADIOA_1TARRAY': ('RF', 2),
    'RTL8188EEMAC_1T_ARRAY': ('MAC', 2),
    'RTL8188EEAGCTAB_1TARRAY': ('AGC', 2),
}
out = ['// SPDX-License-Identifier: GPL-2.0',
       '// Copyright(c) 2009-2013 Realtek Corporation.',
       '// Generated by make_tables.py from complete Linux rtl8188ee/table.c.',
       '// source sha256: ' + hashlib.sha256(source.encode()).hexdigest()]
for name, body in re.findall(r'u32\s+(\w+)\[\]\s*=\s*\{(.*?)\};', source, re.S):
    target, stride = names[name]
    values = [int(value, 16) for value in re.findall(r'0x[0-9a-fA-F]+', body)]
    assert len(values) % stride == 0
    # Current source contains no conditional branches. Never silently flatten
    # a future board/cut-conditioned table into an unconditional program.
    assert all(value < 0xcdcdcdcd for value in values[::stride])
    out.append(f'pub(super) const {target}: &[[u32; {stride}]] = &[')
    for start in range(0, len(values), stride):
        out.append('    [' + ', '.join(f'0x{v:08x}' for v in values[start:start+stride]) + '],')
    out.append('];')
Path(__file__).with_name('tables.rs').write_text('\n'.join(out) + '\n')
