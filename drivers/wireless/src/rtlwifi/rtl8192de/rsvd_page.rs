/// `H2C_RSVDPAGE` location command (`fw.h:33-38`): byte 0 is the
/// probe-response page, byte 1 the PS-Poll page, byte 2 the Null page.
pub const RSVDPAGE_LOCATION: [u8; 3] = [PROBERSP_PG as u8, PSPOLL_PG as u8, NULL_PG as u8];

/// `rtl92d_set_fw_rsvdpagepkt` page bodies: beacon A2 (own) / A3
/// (BSSID — A1 stays broadcast); PS-Poll AID `| 0xc000`, BSSID, TA;
/// Null and probe response A1 (BSSID) / A2 (own) / A3 (BSSID).
/// `Err(Error::Packet)` for an AID outside 1..=2007 — the NARF
/// admission, as in `rtl8192ce`'s `station_control::reserved_pages`
/// (Linux ORs `0xc000` onto whatever AID it is given).
pub fn pages(own: [u8; 6], bssid: [u8; 6], aid: u16) -> Result<[u8; LEN], Error> {
    if !(1..=2007).contains(&aid) {
        return Err(Error::Packet);
    }
    let mut bytes = TEMPLATE;
    bytes[10..16].copy_from_slice(&own);
    bytes[16..22].copy_from_slice(&bssid);
    let at = PSPOLL_PG * PAGE;
    bytes[at + 2..at + 4].copy_from_slice(&(aid | 0xc000).to_le_bytes());
    bytes[at + 4..at + 10].copy_from_slice(&bssid);
    bytes[at + 10..at + 16].copy_from_slice(&own);
    for page in [NULL_PG, PROBERSP_PG] {
        let at = page * PAGE;
        bytes[at + 4..at + 10].copy_from_slice(&bssid);
        bytes[at + 10..at + 16].copy_from_slice(&own);
        bytes[at + 16..at + 22].copy_from_slice(&bssid);
    }
    Ok(bytes)
}

/// `rtl92de_tx_polling(hw, BEACON_QUEUE)` (`trx.c:816-826`): the
/// beacon-queue doorbell is `REG_PCIE_CTRL_REG` word `BIT(4)`.
pub fn tx_polling(io: &impl Io) -> Result<(), Error> {
    io.write16(super::mac::REG_PCIE_CTRL_REG, 1 << 4)?;
    Ok(())
}

/// `rtl92de_tx_fill_cmddesc` (`trx.c:658-716`) over beacon descriptor
/// 0 plus the OWN publication at its end: `fill_cmd` (offset `0x20`,
/// 1M on 2.4 GHz / 6M on 5 GHz, sequence 0, `QSLT_BEACON`, first+last
/// segment, buffer length/address, rate id 7, MAC id 0, `use_rate`,
/// the LPS hwseq rule), then OWN. Linux's
/// `clear_pci_tx_desc_content` clears only the first 40 bytes, so the
/// ring link at dword 10 survives a fill; it is preserved here.
pub fn fill_cmd_desc(slot: &mut TxDesc, buffer_addr: u32, band_5g: bool, fwctrl_lps: bool) {
    let next = slot.dw[10];
    *slot = TxDesc::fill_cmd(LEN as u16, buffer_addr, band_5g, fwctrl_lps);
    slot.dw[10] = next;
    slot.set_own(true);
}

/// Caller-owned upload sink for [`set_fw_rsvdpagepkt`]: beacon
/// descriptor 0 and the 768-byte packet buffer it points at, with the
/// buffer's DMA address. Both live in host memory (the ring owner
/// holds them); only the doorbell and the H2C location go through
/// register I/O.
#[derive(Debug)]
pub struct Upload<'a> {
    /// BEACON_QUEUE descriptor 0.
    pub desc: &'a mut TxDesc,
    /// 768-byte packet buffer (`pages` are copied in here).
    pub packet: &'a mut [u8; LEN],
    /// DMA address of `packet` (descriptor dword 8).
    pub buffer_addr: u32,
    /// Station MAC (`mac->mac_addr`).
    pub own: [u8; 6],
    /// BSS BSSID (`mac->bssid`).
    pub bssid: [u8; 6],
    /// 5 GHz band (`rtlhal->current_bandtype == BAND_ON_5G`).
    pub band_5g: bool,
    /// Firmware LPS control (`ppsc->fwctrl_lps`).
    pub fwctrl_lps: bool,
}

/// `rtl92d_set_fw_rsvdpagepkt(hw, 0)` (`fw.c:595`): patch the pages,
/// copy them into the caller's buffer, fill beacon descriptor 0 with
/// `rtl92de_tx_fill_cmddesc` (OWN published), ring the beacon
/// doorbell (`rtl92de_tx_polling(hw, BEACON_QUEUE)`), and send the
/// `H2C_RSVDPAGE` location command — in that order, and the location
/// only when the upload succeeded (Linux's `dlok`).
pub async fn set_fw_rsvdpagepkt(
    io: &impl Io,
    mailbox: &mut Mailbox,
    upload: Upload<'_>,
    aid: u16,
    rf_on: bool,
) -> Result<(), Error> {
    let Upload {
        desc,
        packet,
        buffer_addr,
        own,
        bssid,
        band_5g,
        fwctrl_lps,
    } = upload;
    let bytes = pages(own, bssid, aid)?;
    packet.copy_from_slice(&bytes);
    fill_cmd_desc(desc, buffer_addr, band_5g, fwctrl_lps);
    tx_polling(io)?;
    mailbox
        .fill(io, super::h2c::H2C_RSVDPAGE, &RSVDPAGE_LOCATION, rf_on)
        .await
}
