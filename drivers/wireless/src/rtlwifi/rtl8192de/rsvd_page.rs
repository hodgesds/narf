//! RTL8192DE reserved-page packet (`rtl92d_set_fw_rsvdpagepkt`).
//!
//! Linux v6.1 `rtl8192de/fw.c:595` (page defines + template `fw.c:479-593`,
//! `fw.h:33-38` page-location macros, `base.h:40-64` 802.11 header
//! offsets, `trx.c:658-716` `rtl92de_tx_fill_cmddesc`,
//! `trx.c:816-826` `rtl92de_tx_polling`, `rtl8192d/reg.h:138`
//! `REG_PCIE_CTRL_REG`, `wifi.h` `enum rtl8192c_h2c_cmd`): on station
//! connect the driver uploads a 768-byte reserved-page packet
//! (`TOTAL_RESERVED_PKT_LEN`, six 128-byte pages — beacon 0..=1,
//! PS-Poll 2, Null 3, probe response 4..=5) on the BEACON_QUEUE
//! descriptor 0 and then tells the firmware the page locations with
//! the 3-byte `H2C_RSVDPAGE` (3) mailbox command (`[4, 2, 3]`:
//! probe-response page, PS-Poll page, Null page).
//!
//! [`TEMPLATE`] is the Linux initializer transcribed verbatim by
//! `gen_rsvd_page.py` (never hand-copied); [`pages`] patches only the
//! fields Linux patches — beacon A2 (own MAC) / A3 (BSSID), PS-Poll
//! AID `| 0xc000` / BSSID / TA, Null and probe-response A1 / A2 / A3.
//! Every other byte, including the non-zero tails at the ends of pages
//! 1–3 and the all-zero page 5, is firmware-consumed template data the
//! host never rewrites.
//!
//! [`set_fw_rsvdpagepkt`] is the `_rtl92d_cmd_send_packet` half
//! (`fw.c:454`): the caller-owned 768-byte buffer plus beacon
//! descriptor 0 (Linux's `dev_alloc_skb` + `ring->desc[0]`), filled
//! with [`super::trx::TxDesc::fill_cmd`] and OWN published, then the
//! beacon doorbell (`rtl92de_tx_polling(hw, BEACON_QUEUE)`:
//! `REG_PCIE_CTRL_REG` word `BIT(4)`), then the location command —
//! and the location only when the upload succeeded (Linux's `dlok`).
//! Linux's `dl_finished` parameter is never read and is dropped here,
//! as `fw.rs` drops `rtl92d_write_fw`'s unused `version`.
//!
//! Not modelled: the DMA mapping of the packet buffer (the caller owns
//! the buffer and hands over its DMA address, as the future
//! `Prepared::Chip::Rtl8192de` packet path owns the rings), and the
//! `get_desc(HW_DESC_OWN)` pre-read (Linux discards its result and
//! overwrites descriptor 0 unconditionally).

