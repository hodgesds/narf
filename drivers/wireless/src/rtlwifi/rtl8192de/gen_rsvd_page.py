#!/usr/bin/env python3
"""Generate the RTL8192DE reserved-page packet template verbatim.

Reads Linux ``drivers/net/wireless/realtek/rtlwifi/rtl8192de/fw.c``
(at the pinned tag, v6.1) and emits the ``reserved_page_packet``
initializer (``fw.c:485``, ``TOTAL_RESERVED_PKT_LEN`` 768) as a Rust
``[u8; 768]`` array literal, 16 bytes per line.

Usage:
    gen_rsvd_page.py /path/to/linux/drivers/net/wireless/realtek/rtlwifi/rtl8192de/fw.c

The emitted bytes are the template only: the host patches the address
fields (see ``rsvd_page.rs::pages``) exactly as
``rtl92d_set_fw_rsvdpagepkt`` does. Nothing here is hand-copied: the
script fails unless the initializer holds exactly 768 bytes, and the
SHA-256 it prints must match ``rsvd_page::TEMPLATE_SHA256`` (the
kernel test re-checks the digest).
"""

import hashlib
import re
import sys

EXPECTED_LEN = 768


def extract_bytes(path: str) -> list[int]:
    with open(path, encoding="utf-8") as handle:
        text = handle.read()
    start = text.index("static u8 reserved_page_packet[TOTAL_RESERVED_PKT_LEN] = {")
    end = text.index("};", start)
    body = text[start:end]
    values = [int(token, 16) for token in re.findall(r"0x[0-9a-fA-F]{2}", body)]
    if len(values) != EXPECTED_LEN:
        raise SystemExit(
            f"reserved_page_packet holds {len(values)} bytes, "
            f"expected {EXPECTED_LEN}"
        )
    return values


def main(argv: list[str]) -> int:
    if len(argv) != 2:
        print(__doc__, file=sys.stderr)
        return 2
    values = extract_bytes(argv[1])
    print(f"// Generated by gen_rsvd_page.py from Linux v6.1 fw.c:485 "
          f"({EXPECTED_LEN} bytes).")
    print(f"// SHA-256: {hashlib.sha256(bytes(values)).hexdigest()}")
    print("pub const TEMPLATE: [u8; LEN] = [")
    for offset in range(0, len(values), 16):
        row = ", ".join(f"0x{b:02x}" for b in values[offset:offset + 16])
        print(f"    {row},")
    print("];")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
