#!/usr/bin/env python3
"""Compile the original Broadcom D11 codec; emit bounded-profile digests."""
import argparse
import hashlib
from pathlib import Path
import re
import subprocess
import tempfile

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--linux", type=Path, default=Path("/usr/src/linux"))
parser.add_argument("--check", action="store_true")
args = parser.parse_args()
base = args.linux / "drivers/net/wireless/broadcom/brcm80211"
source_path = base / "brcmutil/d11.c"
source = source_path.read_text()
header = (base / "include/brcmu_d11.h").read_text()
utils = (base / "include/brcmu_utils.h").read_text()
wifi = (base / "include/brcmu_wifi.h").read_text()
cfg = (base / "brcmfmac/cfg80211.c").read_text()
channels = re.search(r"__wl_5ghz_channels\[\] = \{(.*?)\n\};", cfg, re.S).group(1)
channels = [int(value) for value in re.findall(r"CHAN5G\((\d+)\)", channels)]
assert channels and len(channels) == len(set(channels))
mask_start = utils.index("static inline void brcmu_maskset16")
mask_helpers = utils[mask_start:utils.index("/* externs */", mask_start)]
definitions = "\n".join(line for line in wifi.splitlines() if re.match(
    r"#define CH_(?:MAX_2G_CHANNEL|10MHZ_APART|30MHZ_APART|50MHZ_APART|70MHZ_APART)\s", line))
compat = """
#include <stdint.h>
#include <stdio.h>
typedef uint8_t u8; typedef uint16_t u16; typedef uint32_t u32;
static unsigned warnings;
#define WARN_ON(x) ((x) ? (++warnings, 1) : 0)
#define WARN_ONCE(x, ...) WARN_ON(x)
#define EXPORT_SYMBOL(x)
"""
main = r"""
static const unsigned channels5[] = { CHANNELS5 };
static int band(unsigned ch) {
    if (ch >= 1 && ch <= 14) return 0;
    for (unsigned i=0;i<sizeof(channels5)/sizeof(channels5[0]);i++)
        if (channels5[i] == ch) return 1;
    return -1;
}
static uint64_t hash = UINT64_C(14695981039346656037);
static void byte(unsigned x) { hash = (hash ^ (x & 255)) * UINT64_C(1099511628211); }
int main(void) {
    unsigned count=0;
    for (unsigned channel=0;channel<256;channel++) {
        if (band(channel)<0) continue;
        struct brcmu_chan ch={.chspec=0xa5a5,.chnum=channel,
            .bw=BRCMU_CHAN_BW_20,.sb=BRCMU_CHAN_SB_NONE};
        brcmu_d11ac_encchspec(&ch);
        byte(channel);byte(ch.chspec);byte(ch.chspec>>8);count++;
    }
    printf("pub(super) const ENCODE: (usize, u64) = (%u, 0x%016llx);\n",count,(unsigned long long)hash);
    hash=UINT64_C(14695981039346656037);count=0;
    for (unsigned spec=0;spec<65536;spec++) {
        unsigned center=spec & 255, width=spec & BRCMU_CHSPEC_D11AC_BW_MASK;
        // The retained profile rejects malformed/reserved geometry before
        // consuming the reference decoder's primary. 196 bounds the legacy
        // band center and avoids the reference u8's wrap on invalid inputs.
        if (!center || center>196 || (width==BRCMU_CHSPEC_D11AC_BW_20 &&
            (spec & BRCMU_CHSPEC_D11AC_SB_MASK))) continue;
        struct brcmu_chan ch={.chspec=spec};warnings=0;
        brcmu_d11ac_decchspec(&ch);
        if (warnings || band(ch.control_ch_num)!=ch.band) continue;
        if (ch.band==BRCMU_CHAN_BAND_2G &&
            (ch.bw==BRCMU_CHAN_BW_80 || ch.bw==BRCMU_CHAN_BW_160 ||
             (ch.control_ch_num==14 && ch.bw!=BRCMU_CHAN_BW_20))) continue;
        byte(spec);byte(spec>>8);byte(ch.control_ch_num);count++;
    }
    printf("pub(super) const DECODE: (usize, u64) = (%u, 0x%016llx);\n",count,(unsigned long long)hash);
    return 0;
}
""".replace("CHANNELS5", ",".join(map(str, channels)))
translation = compat + definitions + "\n" + header + mask_helpers + re.sub(
    r"^#include[^\n]*", "", source, flags=re.M) + main
with tempfile.TemporaryDirectory(prefix="narf-d11-oracle-") as directory:
    src = Path(directory) / "oracle.c"
    exe = Path(directory) / "oracle"
    src.write_text(translation)
    subprocess.run(["cc", "-std=c11", "-O2", str(src), "-o", str(exe)], check=True)
    output = subprocess.check_output([str(exe)], text=True)
digest = hashlib.sha256(source_path.read_bytes()).hexdigest()
output = "// Generated by make_linux_oracle.py from original Linux D11 codec.\n" + (
    f"// d11.c SHA256: {digest}\n") + output
target = Path(__file__).with_name("linux_oracle.rs")
if args.check:
    if not target.exists() or target.read_text() != output:
        raise SystemExit("Linux D11 oracle differs; regenerate and review")
else:
    target.write_text(output)
print(output, end="")
