"""Compile the actual RTL8822CE Linux MAC/FIFO functions over an inert bus.

The inactive continuation deliberately masks CR's DMA/MAC enable bits and
keeps TXPAUSE set; these are explicit bus-adapter projections, not changes to
the extracted Linux functions. No fixture or generated bytes are firmware.
"""
from pathlib import Path
import re
import subprocess
import tempfile

BASE = Path('/usr/src/linux/drivers/net/wireless/realtek/rtw88')
HERE = Path(__file__).parent


def function(source, name):
    match = re.search(r'\b' + name + r'\s*\(', source)
    start = source.rfind('\n', 0, match.start()) + 1
    brace = source.index('{', match.end())
    end, depth = brace + 1, 1
    while depth:
        depth += (source[end] == '{') - (source[end] == '}')
        end += 1
    return source[start:end]


mac = (BASE / 'mac.c').read_text()
chip = (BASE / 'rtw8822c.c').read_text()
names = ['txdma_queue_mapping', 'rtw_set_trx_fifo_info', '__priority_queue_cfg',
         '__priority_queue_cfg_legacy', 'priority_queue_cfg', 'init_h2c',
         'rtw_init_trx_cfg', 'rtw_drv_info_cfg', 'rtw_mac_init']
body = function(chip, 'rtw8822c_mac_init') + '\n' + '\n'.join(function(mac, n) for n in names)
definitions = {}
for source in [(BASE / h).read_text() for h in ['reg.h', 'main.h', 'mac.h', 'bf.h', 'sdio.h']] + [chip]:
    lines = source.splitlines()
    index = 0
    while index < len(lines):
        line = lines[index]
        index += 1
        if line.startswith('#define '):
            name = line.split()[1].split('(')[0]
            definition = line
            while definition.endswith('\\'):
                definition += '\n' + lines[index]
                index += 1
            definitions[name] = definition
needed = set(re.findall(r'\b[A-Z][A-Z0-9_]+\b', body))
while True:
    more = set()
    for name in needed:
        more.update(re.findall(r'\b[A-Z][A-Z0-9_]+\b', definitions.get(name, '')))
    if more <= needed:
        break
    needed |= more
objects = sorted(n for n in needed if n in definitions and not definitions[n].startswith('#define ' + n + '('))
pre = r'''
#include <stdint.h>
#include <stdbool.h>
#include <stdio.h>
#include <string.h>
#include <stdlib.h>
typedef uint8_t u8; typedef uint16_t u16; typedef uint32_t u32;
#define BIT(n) (1U << (n))
#define GENMASK(h,l) ((~0U << (l)) & (~0U >> (31-(h))))
#define EINVAL 22
#define EBUSY 16
#define ENOMEM 12
#define EXPORT_SYMBOL(...)
#define rtw_err(...)
#define RTW_HCI_TYPE_PCIE 1
#define RTW_HCI_TYPE_USB 2
#define RTW_HCI_TYPE_SDIO 3
#define RTW_DMA_MAPPING_EXTRA 0
#define RTW_DMA_MAPPING_LOW 1
#define RTW_DMA_MAPPING_NORMAL 2
#define RTW_DMA_MAPPING_HIGH 3
struct rtw_dev;
struct rtw_rqpn {u32 dma_map_vo,dma_map_vi,dma_map_be,dma_map_bk,dma_map_mg,dma_map_hi;};
struct rtw_page_table {u16 hq_num,nq_num,lq_num,exq_num,gapq_num;};
struct rtw_fifo_conf {u16 rsvd_boundary,rsvd_pg_num,rsvd_drv_pg_num,txff_pg_num,acq_pg_num,rsvd_drv_addr,rsvd_h2c_info_addr,rsvd_h2c_sta_info_addr,rsvd_h2cq_addr,rsvd_cpu_instr_addr,rsvd_fw_txbuf_addr,rsvd_csibuf_addr;const struct rtw_rqpn*rqpn;};
struct ops {int (*mac_init)(struct rtw_dev*);};
struct rtw_chip_info {u32 csi_buf_pg_num,rsvd_drv_pg_num,txff_size,page_size,rxff_size,usb_tx_agg_desc_num;const struct rtw_page_table*page_table;const struct rtw_rqpn*rqpn_table;const struct ops*ops;};
struct rtw_dev {const struct rtw_chip_info*chip;struct rtw_fifo_conf fifo;struct {int bulkout_num,type;}hci;struct{u16 rxfltmap1;u8 cut_version;}hal;};
static u8 regs[0x2000];static int recording=1;
static void trace(int op,int width,u32 reg,u32 value){if(recording)printf("(%d,%d,0x%x,0x%x),\n",op,width,reg,value);}
static u8 rtw_read8(struct rtw_dev*d,u32 r){trace(0,8,r,0);return regs[r];}
static u16 rtw_read16(struct rtw_dev*d,u32 r){u16 v;memcpy(&v,regs+r,2);trace(0,16,r,0);return v;}
static u32 rtw_read32(struct rtw_dev*d,u32 r){u32 v;memcpy(&v,regs+r,4);trace(0,32,r,0);if(r==0x208)v&=~1U;return v;}
static void rtw_write8(struct rtw_dev*d,u32 r,u8 v){if(r==0x100)v&=~0xcf;trace(1,8,r,v);regs[r]=v;if(r==0x254&&(v&4)){u32 head;memcpy(&head,regs+0x244,4);head&=0x3ffff;memcpy(regs+0x10d0,&head,4);memcpy(regs+0x10d4,&head,4);}}
static void rtw_write16(struct rtw_dev*d,u32 r,u16 v){if(r==0x522)v|=255;trace(1,16,r,v);memcpy(regs+r,&v,2);}
static void rtw_write32(struct rtw_dev*d,u32 r,u32 v){trace(1,32,r,v);memcpy(regs+r,&v,4);}
static void rtw_write8_set(struct rtw_dev*d,u32 r,u8 m){rtw_write8(d,r,rtw_read8(d,r)|m);}
static void rtw_write8_clr(struct rtw_dev*d,u32 r,u8 m){rtw_write8(d,r,rtw_read8(d,r)&~m);}
static void rtw_write32_set(struct rtw_dev*d,u32 r,u32 m){rtw_write32(d,r,rtw_read32(d,r)|m);}
static void rtw_write32_clr(struct rtw_dev*d,u32 r,u32 m){rtw_write32(d,r,rtw_read32(d,r)&~m);}
static void rtw_write8_mask(struct rtw_dev*d,u32 r,u32 m,u32 v){rtw_write8(d,r,(rtw_read8(d,r)&~m)|((v<<__builtin_ctz(m))&m));}
static void rtw_write32_mask(struct rtw_dev*d,u32 r,u32 m,u32 v){rtw_write32(d,r,(rtw_read32(d,r)&~m)|((v<<__builtin_ctz(m))&m));}
static int rtw_hci_type(struct rtw_dev*d){return RTW_HCI_TYPE_PCIE;}
static bool rtw_chip_wcpu_8051(struct rtw_dev*d){return false;}
static bool rtw_chip_wcpu_3081(struct rtw_dev*d){return true;}
static bool check_hw_ready(struct rtw_dev*d,u32 r,u32 m,u32 v){return (rtw_read32(d,r)&m)==v;}
static void rtw_hci_interface_cfg(struct rtw_dev*d){if(d->hal.cut_version>=3)rtw_write32_mask(d,0x3fc,1U<<26,1);}
static const struct rtw_page_table pages[]={{64,64,64,64,1},{64,64,64,64,1}};
static const struct rtw_rqpn queues[]={{2,2,1,1,0,3},{2,2,1,1,0,3}};
'''
post = r'''
int main(int argc,char**argv){
if(argc>1){recording=0;
CONSTANTS
return 0;}
int seed=0,cut=0;while(seed<2){for(int i=0;i<sizeof(regs);i++)regs[i]=(u8)(i*17+seed*83);u32 sys=(u32)cut<<12;memcpy(regs+0xf0,&sys,4);printf("TRACE %d\n",seed);
const struct ops ops={rtw8822c_mac_init};const struct rtw_chip_info chip={50,16,262144,128,24576,3,pages,queues,&ops};struct rtw_dev d={.chip=&chip,.hci={.type=RTW_HCI_TYPE_PCIE}};d.hal.cut_version=(rtw_read32(&d,0xf0)>>12)&15;if(rtw_mac_init(&d))return 1;printf("END\n");seed++;cut=3;}
return 0;}
'''.replace('CONSTANTS', '\n'.join(f'printf("{n} %u\\n", (unsigned)({n}));' for n in objects))
with tempfile.TemporaryDirectory() as temp:
    source, exe = Path(temp) / 'mac.c', Path(temp) / 'mac'
    source.write_text(pre + '\n' + '\n'.join(definitions[n] for n in sorted(needed) if n in definitions) + '\n' + body + post)
    subprocess.run(['cc', '-O2', '-o', str(exe), str(source)], check=True)
    constants = subprocess.check_output([str(exe), 'constants']).decode().splitlines()
    traces = subprocess.check_output([str(exe)]).decode()
values = '// Evaluated from current Linux rtw88 headers and rtw8822c.c.\n'
for line in constants:
    name, value = line.split()
    values += 'pub const %s: %s = 0x%x;\n' % (name, 'u16' if name.startswith('REG_') and int(value) <= 65535 else 'u32', int(value))
(HERE / 'values.rs').write_text(values)
golden = '// Original Linux MAC/FIFO functions through an explicitly inactive bus adapter.\n'
for seed, trace in re.findall(r'TRACE (\d+)\n(.*?)END\n', traces, re.S):
    golden += 'const LINUX_MAC_%s: &[(u8,u8,u16,u32)] = &[\n%s];\n' % (seed, trace)
(HERE / 'golden.rs').write_text(golden)
subprocess.run(['rustfmt', '--edition', '2021', str(HERE / 'values.rs'), str(HERE / 'golden.rs')], check=True)
