#!/usr/bin/env python3
"""Generate rtl8723b_tables.rs verbatim from Linux rtl8xxxu/8723b.c.

usage: gen_rtl8723b_tables.py <linux>/drivers/net/wireless/realtek/rtl8xxxu/8723b.c > rtl8723b_tables.rs
"""
import re
import sys

TABLES = [
    ("rtl8723b_mac_init_table", "MAC_INIT_TABLE", "MacRow", "m", 2),
    ("rtl8723b_phy_1t_init_table", "PHY_INIT_TABLE", "Reg32Val", "p", 8),
    ("rtl8xxx_agc_8723bu_table", "AGC_TABLE", "Reg32Val", "p", 8),
    ("rtl8723bu_radioa_1t_init_table", "RADIO_A_INIT_TABLE", "RfRow", "r", 8),
]


def main():
    src = open(sys.argv[1]).read()
    out = [
        "// @generated by gen_rtl8723b_tables.py from Linux",
        "// drivers/net/wireless/realtek/rtl8xxxu/8723b.c (GPL-2.0-or-later). Do not edit.",
        "//! RTL8723BU MAC/BB/AGC/RF init tables, rows verbatim including the",
        "//! Linux sentinel row.",
        "",
        "use super::phy::Reg32Val;",
        "use super::phy_tables::{MacRow, RfRow};",
        "",
        "const fn m(reg: u16, val: u8) -> MacRow {",
        "    MacRow { reg, val }",
        "}",
        "const fn p(reg: u16, val: u32) -> Reg32Val {",
        "    Reg32Val { reg, val }",
        "}",
        "const fn r(reg: u8, val: u32) -> RfRow {",
        "    RfRow { reg, val }",
        "}",
    ]
    for cname, rname, ty, ctor, width in TABLES:
        m = re.search(r"static const struct \w+ " + cname + r"\[\] = \{(.*?)\n\};", src, re.S)
        if not m:
            sys.exit("missing table " + cname)
        rows = re.findall(r"\{\s*(0x[0-9a-fA-F]+)\s*,\s*(0x[0-9a-fA-F]+)\s*\}", m.group(1))
        out.append("")
        out.append("/// `8723b.c::%s[]` (%d rows + sentinel)." % (cname, len(rows) - 1))
        out.append("pub const %s: &[%s] = &[" % (rname, ty))
        for reg, val in rows:
            out.append("    %s(0x%x, 0x%0*x)," % (ctor, int(reg, 16), width, int(val, 16)))
        out.append("];")
    print("\n".join(out))


main()
