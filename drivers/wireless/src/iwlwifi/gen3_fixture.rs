//! Factual API89 test metadata from the installed Ty/So/Ma images.
//! This creates no executable, PCI, board, key or emission authority.
use alloc::{vec, vec::Vec};

#[derive(Clone, Copy, Debug)]
pub(super) enum Case {
    Ty,
    So,
    SoLong,
    SoImr,
    SoCdb,
    Ma,
}
impl Case {
    pub fn did(self) -> u16 {
        match self {
            Self::Ty => 0x2725,
            Self::So => 0x7af0,
            Self::SoLong | Self::SoCdb => 0x51f0,
            Self::SoImr => 0x51f1,
            Self::Ma => 0x7e40,
        }
    }
    pub fn revision(self) -> u32 {
        match self {
            Self::Ty => 0x420,
            Self::Ma => 0x441,
            _ => 0x370,
        }
    }
    pub fn radio(self) -> u32 {
        0x10d000 | if self.cdb() { 1 << 28 } else { 0 }
    }
    pub fn cdb(self) -> bool {
        matches!(self, Self::SoCdb)
    }
    pub fn soc(self) -> [u8; 8] {
        match self {
            Self::Ty => [1, 0, 0, 0, 244, 1, 0, 0],
            Self::So => [4, 0, 0, 0, 244, 1, 0, 0],
            Self::SoLong | Self::SoImr | Self::SoCdb => [10, 0, 0, 0, 224, 46, 0, 0],
            Self::Ma => [0; 8],
        }
    }
    pub fn commands(self) -> Vec<u8> {
        let mut rows = API89_COMMANDS.to_vec();
        for row in &mut rows {
            if matches!(self, Self::SoCdb) && row[..2] == [10, 4] {
                row[2] = 1;
            }
            if matches!(self, Self::Ma) && matches!(row[..2], [0xf2, 1] | [0xf6, 1]) {
                row[2] = 8;
            }
        }
        rows.into_iter().flatten().collect()
    }
    pub fn image(self) -> Vec<u8> {
        let mut bytes = vec![0; 88];
        bytes[4..8].copy_from_slice(&super::IWL_TLV_UCODE_MAGIC.to_le_bytes());
        bytes[72..76].copy_from_slice(&89u32.to_le_bytes());
        fn tlv(out: &mut Vec<u8>, tag: u32, data: &[u8]) {
            out.extend_from_slice(&tag.to_le_bytes());
            out.extend_from_slice(&(data.len() as u32).to_le_bytes());
            out.extend_from_slice(data);
            out.resize(out.len().next_multiple_of(4), 0);
        }
        tlv(&mut bytes, 48, &self.commands());
        let api = API89_API_WORDS;
        let caps = match self {
            Self::Ty => TY_CAPS,
            Self::SoCdb => SO_CDB_CAPS,
            Self::Ma => MA_CAPS,
            _ => SO_CAPS,
        };
        for (tag, words) in [(29, api), (30, caps)] {
            for (index, bits) in words.into_iter().enumerate() {
                if bits == 0 {
                    continue;
                }
                let mut data = [0; 8];
                data[..4].copy_from_slice(&(index as u32).to_le_bytes());
                data[4..].copy_from_slice(&bits.to_le_bytes());
                tlv(&mut bytes, tag, &data);
            }
        }
        tlv(&mut bytes, 23, &0x330018u32.to_le_bytes());
        bytes
    }
}
