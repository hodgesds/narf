//! Deterministic Rust literal emission from independently decoded metadata.
use super::*;
use std::fmt::Write;
type Item = (String, Value, Extracted);
fn val(value: &Value, key: &str) -> Result<String> {
    let value = value
        .get(key)
        .with_context(|| format!("missing render field {key}"))?;
    ensure!(!value.is_null(), "missing render field {key}");
    Ok(value.to_string())
}
fn fields(out: &mut String, value: &Value, names: &[&str], indent: &str) -> Result<()> {
    for field in names {
        writeln!(out, "{indent}{field}: {},", val(value, field)?)?;
    }
    Ok(())
}
fn list(values: &Value) -> Result<String> {
    Ok(values
        .as_array()
        .context("expected array")?
        .iter()
        .map(Value::to_string)
        .collect::<Vec<_>>()
        .join(", "))
}
pub(super) fn products(vendor: Vendor, items: &[Item]) -> Result<BTreeMap<String, String>> {
    let mut products = BTreeMap::new();
    match vendor {
        Vendor::Intel => {
            let mut out=String::from("// Generated by cargo xtask wifi-fixtures; metadata only, never executable.\n#[rustfmt::skip]\nconst GOLDENS: &[Golden] = &[\n");
            for (key, image, value) in items {
                writeln!(out,"    Golden {{\n        source: {},\n        source_sha256: {},\n        image_len: {},\n        metadata: include_bytes!(\"{key}.metadata.bin\"),\n        fragments: &[",val(image,"source")?,val(image,"source_sha256")?,val(image,"source_size")?)?;
                for (a, b, c) in &value.fragments {
                    writeln!(out, "            ({a}, {b}, {c}),")?;
                }
                out.push_str("        ],\n");
                fields(
                    &mut out,
                    &value.facts,
                    &[
                        "version",
                        "build",
                        "human",
                        "num_cpu",
                        "fw_version",
                        "capabilities",
                        "api_changes",
                        "calibration",
                        "phy_config",
                    ],
                    "        ",
                )?;
                writeln!(
                    out,
                    "        commands: &{:?},",
                    unhex(string(&value.facts, "commands_hex")?)?
                )?;
                fields(&mut out, &value.facts, &["iml_len", "pnvm_len"], "        ")?;
                out.push_str("        sections: &[\n");
                for section in array(&value.facts, "sections")? {
                    writeln!(out, "            ({}),", list(section)?)?;
                }
                out.push_str("        ],\n    },\n");
            }
            out.push_str("];\n");
            products.insert("goldens.rs".into(), out);
        }
        Vendor::Mediatek => {
            let mut out =
                String::from("// Generated factual tables only; no executable or CLC payload.\n");
            for patch in [true, false] {
                let (constant, kind, header, header_kind, region_kind, fields_order, region_fields) =
                    if patch {
                        (
                            "PATCH_GOLDENS",
                            "PatchGolden",
                            "header",
                            "Connac2PatchHdr",
                            "Connac2PatchSection",
                            &[
                                "build_date",
                                "platform",
                                "hw_sw_ver",
                                "patch_ver",
                                "checksum",
                                "n_region",
                            ][..],
                            &["sec_type", "offset", "size", "addr", "len", "sec_key_idx"][..],
                        )
                    } else {
                        (
                            "RAM_GOLDENS",
                            "RamGolden",
                            "trailer",
                            "Connac2FwTrailer",
                            "Connac2FwRegion",
                            &[
                                "chip_id",
                                "eco_code",
                                "n_region",
                                "format_ver",
                                "format_flag",
                                "fw_ver",
                                "build_date",
                                "crc",
                            ][..],
                            &[
                                "decomp_crc",
                                "decomp_len",
                                "decomp_blk_sz",
                                "addr",
                                "len",
                                "feature_set",
                                "region_type",
                            ][..],
                        )
                    };
                writeln!(out, "#[rustfmt::skip]\nconst {constant}: &[{kind}] = &[")?;
                for (key, image, value) in items
                    .iter()
                    .filter(|(key, _, _)| key.ends_with("patch") == patch)
                {
                    writeln!(out,"    {kind} {{\n        source: {},\n        source_sha256: {},\n        image_len: {},\n        metadata: include_bytes!(\"{key}.metadata.bin\"),\n        {header}: {header_kind} {{",val(image,"source")?,val(image,"source_sha256")?,val(image,"source_size")?)?;
                    fields(&mut out, &value.facts, fields_order, "            ")?;
                    out.push_str("        },\n        regions: &[\n");
                    for region in array(&value.facts, "regions")? {
                        let parts = region_fields
                            .iter()
                            .map(|field| Ok(format!("{field}: {}", val(region, field)?)))
                            .collect::<Result<Vec<_>>>()?;
                        writeln!(out, "            {region_kind} {{ {} }},", parts.join(", "))?;
                    }
                    out.push_str("        ],\n    },\n");
                }
                out.push_str("];\n");
            }
            products.insert("goldens.rs".into(), out);
        }
        Vendor::Qualcomm => {
            for (name, constant, kind) in [
                ("ath10k_firmware", "IMAGE_GOLDENS", "ImageGolden"),
                ("ath10k_board", "BOARD_GOLDENS", "BoardGolden"),
                ("ath11k_board", "BOARD_GOLDENS", "BoardGolden"),
                ("ath11k_raw", "RAW_GOLDENS", "RawGolden"),
            ] {
                let mut out=format!("// Generated by cargo xtask wifi-fixtures; opaque payloads omitted.\n#[rustfmt::skip]\nconst {constant}: &[{kind}] = &[\n");
                for (key, image, value) in items {
                    let selected = if key.contains("_api") {
                        "ath10k_firmware"
                    } else if key.ends_with("board2") {
                        if key.starts_with("qca6174") {
                            "ath10k_board"
                        } else {
                            "ath11k_board"
                        }
                    } else {
                        "ath11k_raw"
                    };
                    if selected != name {
                        continue;
                    }
                    writeln!(out,"    {kind} {{\n        metadata: MetadataGolden {{\n            source: {},\n            source_sha256: {},\n            image_len: {},\n            bytes: include_bytes!(\"{key}.metadata.bin\"),",val(image,"source")?,val(image,"source_sha256")?,val(image,"source_size")?)?;
                    let fragments = value
                        .fragments
                        .iter()
                        .map(|(a, b, c)| format!("({a}, {b}, {c})"))
                        .collect::<Vec<_>>()
                        .join(", ");
                    writeln!(out, "            fragments: &[{fragments}],\n        }},")?;
                    if kind == "ImageGolden" {
                        fields(
                            &mut out,
                            &value.facts,
                            &["api", "features", "wmi", "htt"],
                            "        ",
                        )?;
                        for field in ["image", "otp"] {
                            writeln!(out, "        {field}: ({}),", list(&value.facts[field])?)?;
                        }
                    } else if kind == "BoardGolden" {
                        out.push_str("        samples: &[\n");
                        for sample in array(&value.facts, "samples")? {
                            writeln!(out,"            BoardSample {{ kind: {}, name: {}, offset: {}, len: {} }},",val(sample,"kind")?,val(sample,"name")?,val(sample,"offset")?,val(sample,"size")?)?;
                        }
                        out.push_str("        ],\n");
                    }
                    out.push_str("    },\n");
                }
                out.push_str("];\n");
                products.insert(format!("{name}.rs"), out);
            }
        }
        Vendor::Broadcom => {
            ensure!(items.len() == 1, "Broadcom fixture count");
            let (_, image, value) = &items[0];
            let ram = if value.facts["embedded_ramsize"].is_null() {
                "None".into()
            } else {
                format!("Some({})", value.facts["embedded_ramsize"])
            };
            products.insert("goldens.rs".into(),format!("// Generated factual metadata; no executable image or board qualification.\nconst SOURCE: &str = {};\nconst SOURCE_SHA256: &str = {};\nconst IMAGE_LEN: usize = {};\nconst RESET_VECTOR_WORD: u32 = {};\nconst RAMSIZE: Option<u32> = {ram};\nconst METADATA: &[u8] = include_bytes!(\"bcm43602.metadata.bin\");\nconst FRAGMENTS: &[(usize, usize, usize)] = &[(0, 0, 4), (108, 4, 8)];\n",val(image,"source")?,val(image,"source_sha256")?,val(image,"source_size")?,val(&value.facts,"reset_vector_word")?));
        }
        Vendor::Realtek => {
            products.insert("metadata.rs".into(), realtek(items)?);
        }
    };
    Ok(products)
}
fn realtek(items: &[Item]) -> Result<String> {
    let mut out=String::from("// Generated by cargo xtask wifi-fixtures from pinned raw vendor firmware.\n// Original-file hashes identify originals, never structural zero-payload replays.\n// Metadata only; never register or boot these parser inputs.\n");
    for (kind, fields) in [
        (
            "Source",
            vec![
                ("name", "&'static str"),
                ("sha256", "&'static str"),
                ("length", "usize"),
                ("fragments", "&'static [(usize, &'static [u8])]"),
                ("images", "&'static [Image]"),
            ],
        ),
        (
            "Image",
            vec![
                ("cut", "u8"),
                ("kind", "u8"),
                ("manufacturing", "bool"),
                ("offset", "usize"),
                ("length", "usize"),
                ("version", "u8"),
                ("major", "u8"),
                ("minor", "u8"),
                ("header_length", "usize"),
                ("dynamic", "bool"),
                ("sections", "&'static [Section]"),
            ],
        ),
        (
            "Section",
            vec![
                ("kind", "u8"),
                ("address", "u32"),
                ("length", "u32"),
                ("checksum", "bool"),
                ("redownload", "bool"),
                ("offset", "usize"),
                ("pool", "Option<Pool>"),
            ],
        ),
        (
            "Pool",
            vec![
                ("offset", "usize"),
                ("length", "usize"),
                ("signatures_offset", "usize"),
                ("signature_length", "usize"),
                ("signature_count", "usize"),
                ("bitmap", "bool"),
            ],
        ),
    ] {
        writeln!(out, "#[derive(Debug)]\npub struct {kind} {{")?;
        for (name, kind) in fields {
            writeln!(out, "    pub {name}: {kind},")?;
        }
        out.push_str("}\n");
    }
    for (index, (_, _, value)) in items.iter().enumerate() {
        let source = &value.facts;
        writeln!(out, "pub const SOURCE_{index}: Source = Source {{")?;
        fields(&mut out, source, &["name", "sha256", "length"], "    ")?;
        out.push_str("    fragments: &[\n");
        for part in array(source, "fragments")? {
            let bytes = unhex(string(part, "hex")?)?;
            writeln!(
                out,
                "        ({}, &[{}]),",
                val(part, "offset")?,
                bytes
                    .iter()
                    .map(|x| format!("0x{x:02x}"))
                    .collect::<Vec<_>>()
                    .join(", ")
            )?;
        }
        out.push_str("    ],\n    images: &[\n");
        for image in array(source, "images")? {
            out.push_str("        Image {\n");
            fields(
                &mut out,
                image,
                &[
                    "cut",
                    "kind",
                    "manufacturing",
                    "offset",
                    "length",
                    "version",
                    "major",
                    "minor",
                    "header_length",
                    "dynamic",
                ],
                "            ",
            )?;
            out.push_str("            sections: &[\n");
            for section in array(image, "sections")? {
                out.push_str("                Section {\n");
                fields(
                    &mut out,
                    section,
                    &[
                        "kind",
                        "address",
                        "length",
                        "checksum",
                        "redownload",
                        "offset",
                    ],
                    "                    ",
                )?;
                if section["pool"].is_null() {
                    out.push_str("                    pool: None,\n");
                } else {
                    out.push_str("                    pool: Some(Pool {\n");
                    fields(
                        &mut out,
                        &section["pool"],
                        &[
                            "offset",
                            "length",
                            "signatures_offset",
                            "signature_length",
                            "signature_count",
                            "bitmap",
                        ],
                        "                        ",
                    )?;
                    out.push_str("                    }),\n");
                }
                out.push_str("                },\n");
            }
            out.push_str("            ],\n        },\n");
        }
        out.push_str("    ],\n};\n");
    }
    out.push_str("pub const AX: &[Source] = &[\n");
    for (index, (_, _, item)) in items.iter().enumerate() {
        if string(&item.facts, "name")?.starts_with("rtw89/") {
            writeln!(out, "    SOURCE_{index},")?;
        }
    }
    out.push_str("];\n");
    Ok(out)
}
