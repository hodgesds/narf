//! Fixed mode tables for EDID modes that carry no timing of their own: CTA-861
//! Video Identification Codes, VESA DMT (standard timings) and the
//! established timings. Generated from Linux `drivers/gpu/drm/drm_edid.c`
//! (`edid_cea_modes_1`, `edid_cea_modes_193`, `drm_dmt_modes`,
//! `edid_est_modes`); the lookups follow `drm_display_mode_from_vic_index`,
//! `drm_mode_std`/`drm_mode_find_dmt` and `add_established_modes`. CVT/GTF
//! synthesis for standard timings outside DMT is not implemented.
use crate::DetailedTiming;

const PHSYNC: u8 = 1;
const PVSYNC: u8 = 2;
const INTERLACE: u8 = 4;
const DBLCLK: u8 = 8;
const DBLSCAN: u8 = 16;

/// One `DRM_MODE(...)` entry: pixel clock, horizontal and vertical
/// (display, sync start, sync end, total) and flags.
#[derive(Copy, Clone, Debug, PartialEq, Eq)]
pub struct FixedMode {
    pub clock_khz: u32,
    pub h: [u16; 4],
    pub v: [u16; 4],
    flags: u8,
}

impl FixedMode {
    const fn new(clock_khz: u32, h: [u16; 4], v: [u16; 4], flags: u8) -> Self {
        Self {
            clock_khz,
            h,
            v,
            flags,
        }
    }
    pub fn interlaced(self) -> bool {
        self.flags & INTERLACE != 0
    }
    /// Pixel-repeated (DBLCLK) modes: the active width counts each pixel
    /// twice on the wire.
    pub fn pixel_repeated(self) -> bool {
        self.flags & DBLCLK != 0
    }
    /// `drm_mode_vrefresh`: rounded Hz, doubled for interlace and halved
    /// for double scan.
    pub fn refresh_hz(self) -> u32 {
        let total = u64::from(self.h[3]) * u64::from(self.v[3]);
        if total == 0 {
            return 0;
        }
        let mut num = u64::from(self.clock_khz) * 1000;
        let mut den = total;
        if self.interlaced() {
            num *= 2;
        }
        if self.flags & DBLSCAN != 0 {
            den *= 2;
        }
        ((num + den / 2) / den) as u32
    }
    /// Linux `mode_is_rb`: CVT reduced blanking.
    fn reduced_blanking(self) -> bool {
        self.h[3] - self.h[0] == 160
            && self.h[2] - self.h[0] == 80
            && self.h[2] - self.h[1] == 32
            && self.v[1] - self.v[0] == 3
    }
    /// The mode as a detailed timing (blanking, sync offset and width from
    /// the DRM fields).
    pub fn detailed(self) -> DetailedTiming {
        DetailedTiming {
            pixel_clock_khz: self.clock_khz,
            h_active: self.h[0],
            h_blanking: self.h[3] - self.h[0],
            v_active: self.v[0],
            v_blanking: self.v[3] - self.v[0],
            h_sync_offset: self.h[1] - self.h[0],
            h_sync_width: self.h[2] - self.h[1],
            v_sync_offset: (self.v[1] - self.v[0]) as u8,
            v_sync_width: (self.v[2] - self.v[1]) as u8,
            h_image_mm: 0,
            v_image_mm: 0,
            interlaced: self.interlaced(),
            h_sync_positive: self.flags & PHSYNC != 0,
            v_sync_positive: self.flags & PVSYNC != 0,
        }
    }
}

/// The CTA-861 mode of a VIC, if Linux knows it.
pub fn cea_mode(vic: u8) -> Option<FixedMode> {
    match vic {
        1..=127 => CEA_MODES_1.get(usize::from(vic) - 1).copied(),
        193.. => CEA_MODES_193.get(usize::from(vic) - 193).copied(),
        _ => None,
    }
}

/// `add_established_modes`: established timings I/II (bytes 35 and 36) and
/// the manufacturer byte's bit 7.
pub fn established_modes(t1: u8, t2: u8, manufacturer: u8) -> impl Iterator<Item = FixedMode> {
    let bits = u32::from(t1) | u32::from(t2) << 8 | (u32::from(manufacturer) & 0x80) << 9;
    ESTABLISHED_MODES
        .into_iter()
        .enumerate()
        .filter(move |(i, _)| bits & (1 << i) != 0)
        .map(|(_, m)| m)
}

/// `drm_mode_std` for one standard timing (bytes `b0`, `b1`), as far as a
/// VESA DMT mode covers it: None for unused slots and for sizes DMT does not
/// list (Linux then synthesizes CVT/GTF), and for the 1366x768 HDTV case
/// Linux also synthesizes. `revision` is the EDID revision (aspect 0 means
/// 16:10 from 1.3, 1:1 before).
pub fn standard_mode(b0: u8, b1: u8, revision: u8) -> Option<FixedMode> {
    // bad_std_timing: 0x0101 and 0x0000 are unused.
    if (b0 == 1 && b1 == 1) || (b0 == 0 && b1 == 0) {
        return None;
    }
    let h = u32::from(b0) * 8 + 248;
    let refresh = u32::from(b1 & 0x3f) + 60;
    let v = match b1 >> 6 {
        0 if revision < 3 => h,
        0 => h * 10 / 16,
        1 => h * 3 / 4,
        2 => h * 4 / 5,
        _ => h * 9 / 16,
    };
    if refresh == 60 && ((h == 1360 && v == 765) || (h == 1368 && v == 769)) {
        return None;
    }
    find_dmt(h, v, refresh, false)
}

/// `drm_mode_find_dmt`: the DMT mode of that size and refresh, with or
/// without reduced blanking.
pub fn find_dmt(h: u32, v: u32, refresh: u32, rb: bool) -> Option<FixedMode> {
    DMT_MODES.into_iter().find(|m| {
        u32::from(m.h[0]) == h
            && u32::from(m.v[0]) == v
            && m.refresh_hz() == refresh
            && m.reduced_blanking() == rb
    })
}

/// A progressive mode with the given sync polarities, to match against the
/// tables.
pub const fn progressive(
    clock_khz: u32,
    h: [u16; 4],
    v: [u16; 4],
    h_sync_positive: bool,
    v_sync_positive: bool,
) -> FixedMode {
    let mut flags = 0;
    if h_sync_positive {
        flags |= PHSYNC;
    }
    if v_sync_positive {
        flags |= PVSYNC;
    }
    FixedMode::new(clock_khz, h, v, flags)
}

/// HDMI `hdmi_picture_aspect` of a CTA mode: 0 none, 1 4:3, 2 16:9,
/// 3 64:27, 4 256:135.
pub fn cea_aspect(vic: u8) -> u8 {
    match vic {
        1..=127 => CEA_ASPECT_1[usize::from(vic) - 1],
        193.. => CEA_ASPECT_193
            .get(usize::from(vic) - 193)
            .copied()
            .unwrap_or(0),
        _ => 0,
    }
}

/// `cea_mode_alternate_clock`: the 59.94 Hz clock of a 60 Hz-family mode, or
/// the 60 Hz clock of a 240/480-line one (stored at 59.94 Hz).
fn alternate_clock(m: FixedMode) -> u32 {
    if m.refresh_hz() % 6 != 0 {
        return m.clock_khz;
    }
    let (num, den) = if m.v[0] == 240 || m.v[0] == 480 {
        (1001, 1000)
    } else {
        (1000, 1001)
    };
    ((u64::from(m.clock_khz) * num + den / 2) / den) as u32
}

/// `KHZ2PICOS` equality with the mode's 60 Hz or 59.94 Hz clock, then
/// `drm_mode_match` on timings and flags (no aspect: narf modes carry none).
fn matches(to: FixedMode, m: FixedMode) -> bool {
    let picos = |khz: u32| 1_000_000_000 / khz.max(1);
    to.clock_khz != 0
        && (picos(to.clock_khz) == picos(m.clock_khz)
            || picos(to.clock_khz) == picos(alternate_clock(m)))
        && to.h == m.h
        && to.v == m.v
        && to.flags == m.flags
}

/// `drm_match_cea_mode` for a mode without a picture aspect: the lowest VIC
/// whose timing it is, else 0. (The alternate front porches Linux also tries
/// exist only for double-clocked 240p/288p modes, which never match a
/// progressive mode.)
pub fn match_cea_mode(to: FixedMode) -> u8 {
    (1..=127u8)
        .chain(193..=219)
        .find(|&vic| cea_mode(vic).is_some_and(|m| matches(to, m)))
        .unwrap_or(0)
}

/// `drm_match_hdmi_mode`: the HDMI 1.4b VIC (1..=4) of a 4K mode, else 0.
pub fn match_hdmi_mode(to: FixedMode) -> u8 {
    HDMI_MODES
        .iter()
        .position(|&m| matches(to, m))
        .map_or(0, |i| i as u8 + 1)
}

/// The picture aspect of an HDMI 1.4b VIC, as `cea_aspect`.
pub fn hdmi_aspect(vic: u8) -> u8 {
    match vic {
        1..=3 => 2,
        4 => 4,
        _ => 0,
    }
}

