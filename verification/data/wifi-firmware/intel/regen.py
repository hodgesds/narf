#!/usr/bin/env python3
"""Check/extract factual iwlwifi metadata from SHA256-pinned local firmware.

No firmware instructions are copied. The packed metadata contains the 88-byte
header, every TLV header and section destination, plus API/version records.
Rust tests replay these fragments into zero-filled structural images. Those
images are parser fixtures, never loadable firmware or hardware validation.
"""

import argparse
import hashlib
import json
from pathlib import Path
import struct


SOURCES = (
    ("cc_77", "iwlwifi-cc-a0-77.ucode", 1368096,
     "d23a382871e6e638957845b47424ab98dca5e68e022ab73eeeebb0b6f751d7e9"),
    ("ty_89", "iwlwifi-ty-a0-gf-a0-89.ucode", 1678816,
     "0dbdd040e9a74be912d338e20931bba5f8389dfbab5d000c7afa276119034f2c"),
    ("so_gf_89", "iwlwifi-so-a0-gf-a0-89.ucode", 1736748,
     "c569c4b0ffe2054a1cedd5affccff2da8515325eeb23f788c7abe9463d1a1514"),
    ("so_gf4_89", "iwlwifi-so-a0-gf4-a0-89.ucode", 1591720,
     "3019ad402ffd6f4f00e2ecf17995cd0c97292ffc7455b0726795d19e53581bce"),
    ("bz_100", "iwlwifi-bz-b0-gf-a0-100.ucode", 1836712,
     "eef51288bef91cfa40d31b9b3f352e67fa675b3a335b3d9b7328f8de06d47807"),
    ("sc_103", "iwlwifi-sc-a0-wh-b0-c103.ucode", 2226060,
     "08e748dec1e76a87731d844326c19c8f690add41feff0b691088761b13290a04"),
    ("sc_fm_103", "iwlwifi-sc-a0-fm-c0-c103.ucode", 2326720,
     "cce159597d0b8915e3d1166a8680c00a3c12133c4c2ec577d7f09f60636edd9c"),
)


def extract(blob):
    assert len(blob) >= 88 and blob[:8] == b"\0\0\0\0IWL\n", "bad Intel header"
    # Keep the independent wire decoder separate from the Rust production code.
    fragments = [(0, blob[:88])]
    sections = []
    api_changes = [0] * 8
    capabilities = [0] * 8
    calibration = [0, 0]
    phy_config = 0
    commands = b""
    fw_version = None
    num_cpu = 1
    iml_len = 0
    pnvm_len = 0
    tags = {}
    cursor = 88
    while cursor < len(blob):
        assert cursor + 8 <= len(blob), "truncated TLV header"
        tag, length = struct.unpack_from("<II", blob, cursor)
        data_offset = cursor + 8
        end = data_offset + length
        padded_end = data_offset + ((length + 3) & ~3)
        assert end <= padded_end <= len(blob), "truncated TLV data/padding"
        data = blob[data_offset:end]
        fragments.append((cursor, blob[cursor:data_offset]))
        tags[str(tag)] = tags.get(str(tag), 0) + 1
        if tag in (19, 20, 24, 25):
            assert length >= 4
            destination, = struct.unpack_from("<I", data)
            sections.append((tag, destination, length - 4))
            fragments.append((data_offset, data[:4]))
        elif tag in (22, 23, 27, 29, 30, 36, 48, 62):
            fragments.append((data_offset, data))
        if tag == 22:
            ucode_type, flow, event = struct.unpack("<III", data)
            if ucode_type == 0:
                calibration = [flow, event]
        elif tag == 23:
            phy_config, = struct.unpack_from("<I", data)
        elif tag == 27:
            num_cpu, = struct.unpack_from("<I", data)
        elif tag in (29, 30):
            index, bits = struct.unpack("<II", data)
            words = api_changes if tag == 29 else capabilities
            if index < len(words):
                words[index] |= bits
        elif tag == 36:
            fw_version = list(struct.unpack_from("<III", data))
        elif tag == 48:
            assert length % 4 == 0
            commands = data
        elif tag == 52:
            iml_len = length
        elif tag == 74:
            pnvm_len = length
        cursor = padded_end
    assert cursor == len(blob)
    packed = bytearray()
    ranges = []
    for offset, data in fragments:
        if data:
            ranges.append((offset, len(packed), len(data)))
            packed.extend(data)
    return bytes(packed), ranges, {
        "version": struct.unpack_from("<I", blob, 72)[0],
        "build": struct.unpack_from("<I", blob, 76)[0],
        "human": blob[8:72].split(b"\0", 1)[0].decode("ascii"),
        "num_cpu": num_cpu,
        "fw_version": fw_version,
        "sections": sections,
        "api_changes": api_changes,
        "capabilities": capabilities,
        "calibration": calibration,
        "phy_config": phy_config,
        "commands_hex": commands.hex(),
        "iml_len": iml_len,
        "pnvm_len": pnvm_len,
        "tlv_counts": tags,
    }


def rust_array(values):
    return "[" + ", ".join(str(value) for value in values) + "]"


def outputs(root):
    result = {}
    manifests = []
    lines = ["// Generated by regen.py from pinned factual metadata; no executable firmware.",
             "#[rustfmt::skip]", "const GOLDENS: &[Golden] = &["]
    for key, name, size, digest in SOURCES:
        blob = (root / name).read_bytes()
        if len(blob) != size or hashlib.sha256(blob).hexdigest() != digest:
            raise ValueError(f"unpinned input: {name}")
        packed, ranges, facts = extract(blob)
        result[f"{key}.metadata.bin"] = packed
        manifests.append({"source": name, "source_size": size, "source_sha256": digest,
                          "metadata_sha256": hashlib.sha256(packed).hexdigest(),
                          "metadata_size": len(packed), "facts": facts})
        lines.extend(["    Golden {", f"        source: {json.dumps(name)},",
                      f"        source_sha256: {json.dumps(digest)},", f"        image_len: {size},",
                      f'        metadata: include_bytes!("{key}.metadata.bin"),',
                      "        fragments: &["])
        lines.extend(f"            ({offset}, {start}, {length})," for offset, start, length in ranges)
        lines.extend(["        ],", f"        version: {facts['version']},", f"        build: {facts['build']},",
                      f"        human: {json.dumps(facts['human'])},", f"        num_cpu: {facts['num_cpu']},",
                      f"        fw_version: {rust_array(facts['fw_version'])},",
                      f"        capabilities: {rust_array(facts['capabilities'])},",
                      f"        api_changes: {rust_array(facts['api_changes'])},",
                      f"        calibration: {rust_array(facts['calibration'])},",
                      f"        phy_config: {facts['phy_config']},",
                      f"        commands: &{rust_array(bytes.fromhex(facts['commands_hex']))},",
                      f"        iml_len: {facts['iml_len']},", f"        pnvm_len: {facts['pnvm_len']},",
                      "        sections: &["])
        lines.extend(f"            ({tag}, {destination}, {length})," for tag, destination, length in facts["sections"])
        lines.extend(["        ],", "    },"])
    lines.append("];\n")
    result["goldens.rs"] = "\n".join(lines).encode()
    result["provenance.json"] = (json.dumps({
        "kind": "metadata-only structural replay; zeroed opaque gaps; never load into hardware",
        "decoder": "independent Python struct decoder; Linux drivers/net/wireless/intel/iwlwifi/fw/file.h",
        "license_note": "No executable payload copied; original vendor firmware license not supplied by this fixture.",
        "images": manifests,
    }, indent=2, sort_keys=True) + "\n").encode()
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--firmware-root", type=Path, default=Path("/lib/firmware"))
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--write", action="store_true", help="replace generated factual metadata")
    mode.add_argument("--check", action="store_true", help="check generated metadata (default)")
    args = parser.parse_args()
    destination = Path(__file__).resolve().parent
    for name, data in outputs(args.firmware_root).items():
        path = destination / name
        if args.write:
            path.write_bytes(data)
        else:
            assert path.read_bytes() == data, f"stale golden: {path}"
    print(f"Intel firmware metadata matches {len(SOURCES)} SHA256-pinned local images")


if __name__ == "__main__":
    main()
