// ── /proc/iomem ──────────────────────────────────────────────────────
//
// Linux: kernel/resource.c iomem_init_list / proc_iomem_show
// Format: "start-end : Region name\n" (hex, no 0x prefix)
//
// DEFERRED: narf-memory's E820 / ACPI memmap export and the PCIe BAR
// layout haven't been plumbed into a snapshot API yet.
// Placeholder matches the Linux minimal-boot look (single System RAM
// region). Real wiring will land when MM region snapshot is available.

fn gen_iomem() -> Vec<u8> {
    let mut s = String::new();
    let fs = narf_memory::frame_stats();
    // Approximate: total frames * 4 KiB starting at physical 0.
    let end = (fs.total as u64) * 4096;
    if end > 0 {
        let _ = writeln!(s, "00000000-{:08x} : System RAM", end.saturating_sub(1));
    } else {
        let _ = writeln!(s, "00000000-00000000 : System RAM");
    }
    s.into_bytes()
}

