// ── /proc/slabinfo ───────────────────────────────────────────────────
//
// Linux: mm/slab.c slab_proc_show (slabinfo version 2.1)
// Format:
//   slabinfo - version: 2.1
//   # name <active_objs> <num_objs> <objsize> <objperslab> <pagesperslab>
//   #     : tunables <limit> <batchcount> <sharedfactor>
//   #     : slabdata <active_slabs> <num_slabs> <sharedavail>
//   <name> <active> <total> <objsize> <objperslab> <pagesperslab>
//          : tunables 0 0 0 : slabdata <active_slabs> <total_slabs> 0

fn gen_slabinfo() -> Vec<u8> {
    let mut s = String::new();
    let _ = writeln!(s, "slabinfo - version: 2.1");
    let _ = writeln!(
        s,
        "# name            <active_objs> <num_objs> <objsize> <objperslab> <pagesperslab> \
         : tunables <limit> <batchcount> <sharedfactor> \
         : slabdata <active_slabs> <num_slabs> <sharedavail>"
    );

    let stats = narf_memory::slab::stats();
    for cls in stats.classes.iter() {
        if cls.block_size == 0 {
            continue;
        }
        let objs_per_slab = if cls.block_size > 0 {
            (narf_memory::PAGE_SIZE as usize) / cls.block_size
        } else {
            1
        };
        let objs_per_slab = objs_per_slab.max(1);
        // active_slabs ≈ ceil(in_use / objs_per_slab).
        let active_slabs = cls.in_use.div_ceil(objs_per_slab);
        let total_slabs = cls.grown.div_ceil(objs_per_slab);
        let _ = writeln!(
            s,
            "kmalloc-{:<6} {:>8} {:>8} {:>8} {:>8} {:>12} \
             : tunables 0 0 0 \
             : slabdata {:>8} {:>8} 0",
            cls.block_size,
            cls.in_use,
            cls.grown,
            cls.block_size,
            objs_per_slab,
            1, // pages per slab — 1 for small classes
            active_slabs,
            total_slabs,
        );
    }
    s.into_bytes()
}

