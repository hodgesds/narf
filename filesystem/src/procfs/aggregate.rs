//! `/proc` system-state aggregate files.
//!
//! Registers the set of machine-state summary files that standard Linux
//! tools (top, ps, procps-ng, Python's psutil, etc.) read to understand
//! system health:
//!
//!   /proc/stat          — aggregate CPU time + context-switches + forks
//!   /proc/diskstats     — per-block-device I/O counters
//!   /proc/interrupts    — per-IRQ per-CPU fire counts
//!   /proc/softirqs      — per-softirq-type per-CPU counters (stub)
//!   /proc/swaps         — swap area list (header only — NARF has no swap)
//!   /proc/modules       — loadable kernel modules (deferred: LKM agent)
//!   /proc/iomem         — physical memory layout (deferred: MM wiring)
//!   /proc/ioports       — I/O port allocations (deferred: IO crate)
//!   /proc/slabinfo      — slab allocator class breakdown
//!   /proc/vmstat        — VM counter dump (mostly zeroed — deferred)
//!   /proc/zoneinfo      — per-NUMA-node zone breakdown
//!   /proc/buddyinfo     — buddy allocator free list
//!   /proc/pagetypeinfo  — page migration-type counters
//!   /proc/timer_list    — pending high-resolution timers
//!   /proc/locks         — POSIX file lock list (header only)
//!   /proc/devices       — character + block major-number table
//!   /proc/filesystems   — registered filesystem types (extends gen_filesystems)
//!   /proc/consoles      — registered console devices
//!   /proc/misc          — misc character device registrations
//!   /proc/tty/drivers   — TTY driver table
//!   /proc/fb            — framebuffer registrations
//!   /proc/crypto        — cryptographic algorithm listing
//!
//! Linux refs:
//!   fs/proc/stat.c          — show_stat
//!   fs/proc/interrupts.c    — show_interrupts
//!   fs/proc/softirqs.c      — show_softirqs
//!   block/genhd.c           — diskstats_show
//!   mm/vmstat.c             — vmstat_show / zoneinfo_show / buddyinfo_show
//!   mm/slab.c               — slab_proc_show
//!   kernel/time/timer_list.c — show_timer_list
//!   fs/locks.c              — locks_show
//!   fs/proc/devices.c       — devinfo_show
//!   drivers/char/random.c   — (for misc)
//!
//! ## Deferred wiring notes
//!
//! Per-block-device I/O counters (reads/writes/sectors/latency in
//! /proc/diskstats) are zeroed until the block layer exposes per-device
//! counters.  Most /proc/vmstat counters are also zeroed today — wiring
//! them requires adding tracking atomics throughout the MM subsystem.
//!
//! /proc/modules is an empty body until Wave-21 (LKM agent) registers its
//! module list through `register_modules_snapshot_hook`.
//!
//! /proc/iomem and /proc/ioports use placeholder "00000000-00000000 :
//! System RAM" lines pending real E820 / ACPI region export from the MM
//! and IO subsystems.

