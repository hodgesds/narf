//! 8x8 monochrome ASCII font.
//!
//! Hand-rolled glyphs for printable ASCII 0x20..=0x7E. Format:
//! byte `n` of a glyph is row `n` (0 = top), bit 7 is the leftmost
//! pixel of that row. Letterforms are 5×7 inside an 8×8 cell with
//! one row of bottom padding so consecutive lines have visual gap.
//!
//! Codes outside the printable range (0x00..=0x1F, 0x7F+) render as
//! an empty cell — the framebuffer console treats `\n` separately
//! and never asks for a non-printable glyph.

const EMPTY: [u8; 8] = [0x00; 8];

/// Returns the glyph for ASCII `c`, or EMPTY for non-printable codes.
/// Codes outside the table use the same EMPTY fallback.
pub fn lookup(c: u8) -> [u8; 8] {
    if !(0x20..=0x7E).contains(&c) {
        return EMPTY;
    }
    GLYPHS[(c - 0x20) as usize]
}

